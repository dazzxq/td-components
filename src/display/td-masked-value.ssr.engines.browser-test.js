import { expect } from '@esm-bundle/chai';
// DOM nodes are compared as booleans (`a === b`): a failing chai assertion carrying DOM nodes hangs the runner.
// NO static import of the component: <td-masked-value> is defined LATE (dynamic import below), after the no-JS checks.

// v0.31.0 (ADR 0012, plan docs/internal/plans/v0.31.0-sortable-masked.md M6) — td_masked_value() / <td-masked-value>
// hydrate in place, contract `masked-value@1`. Chromium, Firefox AND WebKit (group `engines`). The markup is EXACTLY what
// php/td.php prints for every case of test/ssr/masked-value.fixtures.json: test/ssr/fixtures/masked-value.html,
// generated by `node test/ssr/build-masked-value-fixture.mjs` and kept fresh by test/php/td-ssr-masked-value.test.js.
const link = document.createElement('link');
link.rel = 'stylesheet';
link.href = '/td.css';
document.head.appendChild(link);
await new Promise((r) => { link.onload = r; link.onerror = r; });

const SPEC = await (await fetch('/test/ssr/masked-value.fixtures.json')).json();
const FIXTURE = await (await fetch('/test/ssr/fixtures/masked-value.html')).text();
const TPL = document.createElement('template');
TPL.innerHTML = FIXTURE;

const root = document.createElement('div');
root.innerHTML = FIXTURE;
document.body.appendChild(root);
const hostOf = (id) => root.querySelector(`section[data-case="${id}"] > td-masked-value`);
const hostHtml = (id) => TPL.content.querySelector(`section[data-case="${id}"] > td-masked-value`).outerHTML;

// Tampered markup: must render safely (masked string from the attribute, no foreign node / handler).
const basic = hostHtml('m-phone');
const MM = {
  'mm-schema': basic.replace('masked-value@1', 'masked-value@2'),
  'mm-onclick': basic.replace('<button ', '<button onclick="window.__pwned = 1" '),
  'mm-extra': basic.replace('<span class="td-sr-only"', '<b>thừa</b><span class="td-sr-only"'),
  'mm-text': basic.replace('>09xx xxx 123</span>', '>0912345123</span>'),
  'mm-type': basic.replace('type="button"', 'type="submit"'),
  'mm-pressed': basic.replace('aria-pressed="false"', 'aria-pressed="true"'),
  'mm-plain': '<td-masked-value label="Tay" masked="09xx xxx 123"></td-masked-value>',
};
const mismatch = document.createElement('div');
mismatch.innerHTML = Object.entries(MM).map(([id, html]) => html.replace('<td-masked-value ', `<td-masked-value id="${id}" `)).join('');
document.body.appendChild(mismatch);

const before = {};
for (const c of SPEC.cases) {
  const host = hostOf(c.id);
  const btn = host.querySelector('button');
  before[c.id] = {
    btn,
    text: host.querySelector('.td-masked__text'),
    box: host.getBoundingClientRect().toJSON(),
    btnBox: btn.getBoundingClientRect().toJSON(),
    visibility: getComputedStyle(btn).visibility,
  };
}

const { TdMaskedValue } = await import('./td-masked-value.js');
const wait = (ms) => new Promise((r) => setTimeout(r, ms));

describe('td-masked-value SSR (masked-value@1) — no JS', () => {
  it('only the masked string shows; the toggle keeps its box but is hidden (visibility)', () => {
    for (const c of SPEC.cases) {
      expect(before[c.id].visibility, c.id).to.equal('hidden');
      expect(before[c.id].btnBox.width, c.id).to.be.greaterThan(0);
    }
  });
});

describe('td-masked-value SSR (masked-value@1) — adopted in place', () => {
  for (const c of SPEC.cases) {
    it(`${c.id}: same nodes, marker consumed, no layout shift, toggle shown; the static hook reveals`, async () => {
      const host = hostOf(c.id);
      const btn = host.querySelector('button.td-masked__toggle');
      expect(btn === before[c.id].btn, 'button node kept').to.equal(true);
      expect(host.querySelector('.td-masked__text') === before[c.id].text, 'text node kept').to.equal(true);
      expect(host.hasAttribute('data-td-ssr')).to.equal(false);
      expect(getComputedStyle(btn).visibility).to.equal('visible');
      const box = host.getBoundingClientRect();
      for (const p of ['x', 'y', 'width', 'height']) expect(Math.abs(box[p] - before[c.id].box[p]), `${c.id} host ${p}`).to.be.at.most(1);
      expect(btn.getAttribute('aria-label')).to.equal(c.expect.name);
      expect(host.querySelector('.td-masked__text').textContent).to.equal(c.expect.masked);
      expect(btn.getAttribute('aria-disabled') === 'true').to.equal(c.expect.disabled);
      for (const bad of c.dropOnHost || []) expect(host.hasAttribute(bad), bad).to.equal(false);
      if (c.expect.dataId) expect(host.dataset.id).to.equal(c.expect.dataId);
      const seen = [];
      TdMaskedValue.reveal = ({ element }) => { seen.push(element.dataset.id ?? null); return Promise.resolve('REAL-1'); };
      const details = [];
      host.addEventListener('revealed', (e) => details.push(e.detail), { once: true });
      btn.click();
      await wait(10);
      TdMaskedValue.reveal = null;
      if (c.expect.disabled) {
        expect(seen.length).to.equal(0);
        return;
      }
      expect(seen).to.deep.equal([c.expect.dataId ?? null]);
      expect(host.querySelector('.td-masked__text').textContent).to.equal('REAL-1');
      expect(details[0]).to.deep.equal({ duration: c.expect.duration });
      expect(!!host.querySelector('td-copy')).to.equal(!!c.expect.copyable);
      host.mask();
      expect(host.querySelector('.td-masked__text').textContent).to.equal(c.expect.masked);
    });
  }
});

describe('td-masked-value SSR — refused markup renders safely', () => {
  for (const id of Object.keys(MM)) {
    it(`${id}: re-rendered from the attributes, nothing foreign`, async () => {
      const host = mismatch.querySelector(`#${id}`);
      expect(host.hasAttribute('data-td-ssr')).to.equal(false);
      expect(host.querySelectorAll('button').length).to.equal(1);
      expect(!!host.querySelector('[onclick], b, button[type="submit"]')).to.equal(false);
      expect(host.querySelector('.td-masked__text').textContent).to.equal('09xx xxx 123');
      expect(host.querySelector('button').getAttribute('aria-pressed')).to.equal('false');
      host.querySelector('button').click();
      await wait(5);
      expect(window.__pwned).to.equal(undefined);
    });
  }
});
