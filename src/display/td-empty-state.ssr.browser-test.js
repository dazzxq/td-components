/**
 * Order-independent serialisation (sorted attributes / class tokens, blank text dropped). `svgByName`: an <svg> is
 * reduced to its `data-icon` (the server fills the icon from the PHP registry — compared by name, not by string).
 */
function serial(node, svgByName = false) {
  if (node.nodeType === Node.TEXT_NODE) return node.data.trim() ? `#${node.data}` : '';
  if (node.nodeType !== Node.ELEMENT_NODE) return '';
  if (svgByName && node.localName === 'svg') return `<svg data-icon=${node.getAttribute('data-icon')}>`;
  const attrs = [...node.attributes]
    .map((a) => `${a.name}=${JSON.stringify(a.name === 'class' ? a.value.split(/\s+/).filter(Boolean).sort().join(' ') : a.value)}`)
    .sort();
  return `<${node.localName} ${attrs.join(' ')}>${[...node.childNodes].map((n) => serial(n, svgByName)).join('')}</${node.localName}>`;
}

