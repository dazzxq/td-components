import { expect } from '@esm-bundle/chai';
// DOM nodes are compared as booleans (`a === b`): a failing chai assertion carrying DOM nodes hangs the runner.
// NO static import of the component: <td-scan-input> is defined LATE (dynamic import below), after the no-JS checks.

// v0.38.0 (ADR 0012, plan v0.38.0-scan-input QĐ 19, M3) — td_scan_input() / <td-scan-input> hydrate, contract
// `scan-input@1`, in Chromium, Firefox AND WebKit (group `engines`). The markup is EXACTLY what php/td.php prints for every
// case of test/ssr/scan-input.fixtures.json: test/ssr/fixtures/scan-input.html, generated by
// `node test/ssr/build-scan-input-fixture.mjs` and kept fresh by test/php/td-ssr-scan-input.test.js.
const link = document.createElement('link');
link.rel = 'stylesheet';
link.href = '/td.css';
document.head.appendChild(link);
await new Promise((r) => { link.onload = r; link.onerror = r; });

const SPEC = await (await fetch('/test/ssr/scan-input.fixtures.json')).json();
const FIXTURE = await (await fetch('/test/ssr/fixtures/scan-input.html')).text();
const TPL = document.createElement('template');
TPL.innerHTML = FIXTURE;

const root = document.createElement('div');
root.innerHTML = FIXTURE;
document.body.appendChild(root);

const hostOf = (id, scope = root) => scope.querySelector(`form[data-case="${id}"] > td-scan-input`);
const hostHtml = (id) => TPL.content.querySelector(`form[data-case="${id}"] > td-scan-input`).outerHTML;
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
async function until(fn, ms = 3000) {
  const t0 = performance.now();
  while (!fn()) {
    if (performance.now() - t0 > ms) throw new Error('timed out waiting');
    await wait(10);
  }
}
const A = '356938035643809';
const B = '490154203237518';

// Hand-written mismatches (must render, never adopt).
const single = hostHtml('s-label-value');
const SINGLE_MM = {
  'mm-onclick': single.replace('<input ', '<input onclick="window.__pwned = 1" '),
  'mm-schema': single.replace('scan-input@1', 'scan-input@2'),
  'mm-hidden-input': single.replace('</div></div>', '</div><input type="hidden" name="code" value="x"></div>'),
  'mm-type': single.replace('type="text"', 'type="password"'),
};
const multi = hostHtml('m-values');
const HIDDEN_A = `<input type="hidden" class="td-scan__hidden" name="imei[]" value="${A}">`;
const MULTI_MM = {
  'mm-hidden-value': multi.replace(HIDDEN_A, HIDDEN_A.replace(A, '111111111111111')),
  'mm-hidden-extra': multi.replace('</td-scan-input>', '<input type="hidden" class="td-scan__hidden" name="imei[]" value="EVIL"></td-scan-input>'),
  'mm-formaction': multi.replace(HIDDEN_A, HIDDEN_A.replace('<input ', '<input formaction="/evil" ')),
  'mm-two-textareas': multi.replace('</textarea>', '</textarea><textarea class="td-scan__fallback" name="imei[]"></textarea>')
    .replace(HIDDEN_A, ''),
  'mm-early': multi.replace(HIDDEN_A, ''),
};
const mismatch = document.createElement('div');
const rename = (html, id) => html.replace(/id="td-(code|imei)-\d+"/, `id="${id}"`).replace(/td-(code|imei)-\d+-input/g, `${id}-input`);
mismatch.innerHTML = [...Object.entries(SINGLE_MM), ...Object.entries(MULTI_MM)]
  .map(([id, html]) => `<form data-case="${id}">${rename(html, id)}</form>`).join('');
document.body.appendChild(mismatch);

// --- before the module loads (no JS) ---
const noJs = {
  fd: new FormData(root.querySelector('form[data-case="m-values"]')).getAll('imei[]'),
  textarea: getComputedStyle(hostOf('m-values').querySelector('textarea')).display,
  box: getComputedStyle(hostOf('m-values').querySelector('.td-scan__box')).display,
  single: getComputedStyle(hostOf('s-basic').querySelector('input')).display,
};
const before = {};
for (const c of SPEC.cases) before[c.id] = hostOf(c.id).querySelector('input');
const multiInput = hostOf('m-values').querySelector('input.td-scan__input');
// text typed by hand before define (one code per line) + a validator assigned early (replayed on upgrade)
hostOf('m-values').querySelector('textarea').value = `${B}\nCCCC03\n\nCCCC03`;
const calls = [];
hostOf('m-values').validate = (value, ctx) => { calls.push([value, ctx.source]); return true; };
// single: the user typed into an adopted field and into a refused one before the upgrade
const pre = hostOf('s-label-value').querySelector('input');
pre.value = 'DH-00';
pre.setSelectionRange(2, 2);
const tampered = mismatch.querySelector('form[data-case="mm-onclick"] input');
tampered.value = 'TYPED-1';
tampered.focus();
tampered.setSelectionRange(3, 3);
// multiple mismatches: one line typed in the textarea; early values on mm-early
for (const id of Object.keys(MULTI_MM)) {
  for (const ta of hostOf(id, mismatch).querySelectorAll('textarea')) ta.value = 'LINE0001';
}
hostOf('mm-early', mismatch).values = ['E1111'];
const warns = [];
const origWarn = console.warn;
console.warn = (...a) => { warns.push(String(a[0])); };

const { TdScanInput } = await import('./td-scan-input.js');
console.warn = origWarn;
await wait(50);

describe('td-scan-input SSR (scan-input@1) — no JS', () => {
  it('multiple: the form submits imei[] from the hidden inputs + the textarea; the textarea shows, the scanner box hides', () => {
    expect(noJs.fd).to.deep.equal(['', A, B]); // tree order: the (empty) textarea, then the hidden inputs
    expect(noJs.textarea).to.not.equal('none');
    expect(noJs.box).to.equal('none');
    expect(noJs.single).to.not.equal('none');
  });
});

describe('td-scan-input SSR — single adopted in place (shared gate)', () => {
  for (const c of SPEC.cases) {
    it(`${c.id}: same input node, marker consumed, value on the host, one FormData entry`, () => {
      const host = hostOf(c.id);
      const input = host.querySelector('input.td-scan__input');
      expect(input === before[c.id], 'input node kept').to.equal(true);
      expect(host.hasAttribute('data-td-ssr')).to.equal(false);
      expect(host instanceof TdScanInput).to.equal(true);
      const want = c.expect;
      expect(host.value).to.equal(want.value);
      expect(input.hasAttribute('name') || input.hasAttribute('value') || input.hasAttribute('required'), 'no-JS attributes removed').to.equal(false);
      if (want.controlId) expect(input.id).to.equal(want.controlId);
      if (want.hostId) expect(host.id).to.equal(want.hostId);
      if (want.label) expect(input.labels[0].textContent).to.equal(want.label);
      if (want.inputmode) expect(input.getAttribute('inputmode')).to.equal(want.inputmode);
      if (want.placeholder) expect(input.getAttribute('placeholder')).to.equal(want.placeholder);
      expect(host.required).to.equal(!!want.required);
      expect(input.disabled).to.equal(!!want.disabled);
      if (want.error) {
        expect(host.querySelector('.td-field-error').textContent).to.equal(want.error);
        expect(input.getAttribute('aria-invalid')).to.equal('true');
      }
      const entries = new FormData(host.closest('form')).getAll('code');
      expect(entries).to.deep.equal(want.disabled ? [] : [want.value]);
      expect(host.querySelector('.td-scan__status') !== null, 'indicator added on bind').to.equal(true);
      for (const bad of c.dropped || []) expect(host.hasAttribute(bad) || input.hasAttribute(bad), bad).to.equal(false);
    });
  }

  it('the text typed before the upgrade + its caret are kept (not the form value)', () => {
    expect(pre.value).to.equal('DH-00');
    expect(pre.selectionStart).to.equal(2);
    expect(hostOf('s-label-value').value).to.equal('DH-0001');
  });

  it('form.reset() → the server value', () => {
    const host = hostOf('s-label-value');
    host.value = 'OTHER';
    host.closest('form').reset();
    expect(host.value).to.equal('DH-0001');
  });
});

describe('td-scan-input SSR — single refused markup renders safely, typed text + focus restored', () => {
  for (const id of Object.keys(SINGLE_MM)) {
    it(`${id}: re-rendered, nothing foreign survives`, () => {
      const host = hostOf(id, mismatch);
      expect(host.hasAttribute('data-td-ssr')).to.equal(false);
      expect(host.querySelectorAll('input').length).to.equal(1);
      expect(!!host.querySelector('[onclick], [style], input[type="hidden"], input[type="password"]')).to.equal(false);
      expect(window.__pwned).to.equal(undefined);
    });
  }

  it('the focused tampered input: text, caret and focus moved to the new input', () => {
    const input = hostOf('mm-onclick', mismatch).querySelector('input');
    expect(input === tampered).to.equal(false);
    expect(input.value).to.equal('TYPED-1');
    expect(document.activeElement === input).to.equal(true);
    expect(input.selectionStart).to.equal(3);
  });
});

describe('td-scan-input SSR — multiple (own gate, review R1-4 / R2-7)', () => {
  it('m-values: same input node, validate called ONCE (the new line), list A B C, FormData = A B C, no-JS parts gone', async () => {
    const host = hostOf('m-values');
    await until(() => host.values.length === 3);
    expect(host.querySelector('input.td-scan__input') === multiInput).to.equal(true);
    expect(calls).to.deep.equal([['CCCC03', 'manual']]);
    expect(host.values).to.deep.equal([A, B, 'CCCC03']);
    expect([...host.querySelectorAll('.td-scan__value')].map((n) => n.textContent)).to.deep.equal(['CCCC03', B, A]);
    expect(new FormData(host.closest('form')).getAll('imei[]')).to.deep.equal([A, B, 'CCCC03']);
    expect(host.querySelectorAll('[name], textarea, input[type="hidden"]').length).to.equal(0);
    expect(host.hasAttribute('data-td-ssr')).to.equal(false);
  });

  it('m-values: form.reset() → the server values (A, B)', () => {
    const host = hostOf('m-values');
    host.closest('form').reset();
    expect(host.values).to.deep.equal([A, B]);
  });

  it('m-xss: values are text; m-empty / m-disabled adopted', () => {
    const x = hostOf('m-xss');
    expect(x.values).to.deep.equal(['<b>x</b>', 'AB', 'A B']);
    expect(x.querySelector('.td-scan__list b') === null).to.equal(true);
    expect(hostOf('m-empty').values).to.deep.equal([]);
    expect(hostOf('m-empty').getAttribute('max')).to.equal('5');
    const d = hostOf('m-disabled');
    expect(d.values).to.deep.equal(['D1111']);
    expect(d.querySelector('input').disabled).to.equal(true);
    expect(new FormData(d.closest('form')).getAll('imei[]')).to.deep.equal([]);
  });

  for (const id of ['mm-hidden-value', 'mm-hidden-extra', 'mm-formaction']) {
    it(`${id}: safe render, list from the server markup NOT taken, FormData only the validated textarea line`, async () => {
      const host = hostOf(id, mismatch);
      await until(() => host.values.length === 1);
      expect(host.values).to.deep.equal(['LINE0001']);
      expect(host.querySelectorAll('input[type="hidden"], textarea, [formaction]').length).to.equal(0);
      expect(new FormData(host.closest('form')).getAll('imei[]')).to.deep.equal(['LINE0001']);
    });
  }

  it('mm-two-textareas: no line captured (ambiguous), list empty', async () => {
    const host = hostOf('mm-two-textareas', mismatch);
    await wait(30);
    expect(host.values).to.deep.equal([]);
    expect(new FormData(host.closest('form')).getAll('imei[]')).to.deep.equal([]);
  });

  it('mm-early: values assigned before the upgrade win over refused markup', async () => {
    const host = hostOf('mm-early', mismatch);
    await until(() => host.values.length === 2);
    expect(host.values).to.deep.equal(['E1111', 'LINE0001']);
  });

  it('exactly one console warning per refused multiple host (none for the adopted ones)', () => {
    const scanWarns = warns.filter((w) => w.startsWith('td-scan-input:'));
    expect(scanWarns.length).to.equal(Object.keys(MULTI_MM).length);
  });
});
