import { expect } from '@esm-bundle/chai';
// DOM nodes are compared as booleans (`a === b`): a failing chai assertion carrying DOM nodes hangs the runner.
// NO static import of the component: <td-number-input> is defined LATE (dynamic import below), after the no-JS checks.

// v0.30.0 (ADR 0012, plan v0.30.0-number-repeater M2 + M3) — td_number_input() element mode / <td-number-input>
// hydrate in place, contract `number-input@1`, in Chromium, Firefox AND WebKit (group `engines`). The markup is EXACTLY
// what php/td.php prints for every case of test/ssr/number.fixtures.json: test/ssr/fixtures/number.html, generated by
// `node test/ssr/build-number-fixture.mjs` and kept fresh by test/php/td-ssr-number.test.js.
const link = document.createElement('link');
link.rel = 'stylesheet';
link.href = '/td.css';
document.head.appendChild(link);
await new Promise((r) => { link.onload = r; link.onerror = r; });

const SPEC = await (await fetch('/test/ssr/number.fixtures.json')).json();
const FIXTURE = await (await fetch('/test/ssr/fixtures/number.html')).text();
const TPL = document.createElement('template');
TPL.innerHTML = FIXTURE;

const root = document.createElement('div');
root.innerHTML = FIXTURE;
document.body.appendChild(root);

const hostOf = (id) => root.querySelector(`form[data-case="${id}"] > td-number-input`);
const hostHtml = (id) => TPL.content.querySelector(`form[data-case="${id}"] > td-number-input`).outerHTML;

// Hand-written mismatches (must render safely, never adopt) — the value of the old control must survive.
const full = hostHtml('n-full'); // host id td-price-2
const MM = {
  'mm-schema': full.replace('number-input@1', 'number-input@2'),
  'mm-onclick': full.replace('<input ', '<input onclick="window.__pwned = 1" '),
  'mm-style': full.replace('<span class="td-number__affix', '<span style="color: red" class="td-number__affix'),
  'mm-live-p': full.replace(/<span class="td-sr-only" ([^>]*)><\/span>/, '<p class="td-sr-only" $1></p>'),
  'mm-extra': full.replace('<div class="td-number__box">', '<div class="td-number__box"><b>thừa</b>'),
  'mm-second-input': full.replace('<span class="td-number__affix', '<input type="hidden" name="price" value="1"><span class="td-number__affix'),
  'mm-name': full.replace(' name="price" value="12990000" label', ' name="other" value="12990000" label'),
  'mm-min': full.replace(' min="1000" suffix', ' min="2000" suffix'),
};
const mismatch = document.createElement('form');
mismatch.innerHTML = Object.entries(MM).map(([id, html]) => html.replaceAll('td-price-2', id)).join('');
document.body.appendChild(mismatch);

// No-JS: native type=number controls, the clean value submits.
const rect = (id) => hostOf(id).getBoundingClientRect();
const boxes0 = Object.fromEntries(SPEC.cases.map((c) => [c.id, rect(c.id)]));
const noJs = {
  type: hostOf('n-full').querySelector('input').type,
  submit: new FormData(root.querySelector('form[data-case="nn-full"]')).get('price'),
  elementSubmit: new FormData(root.querySelector('form[data-case="n-full"]')).get('price'),
};

// State before the module loads: typed value (adopted case), focus (adopted case), early property, refused + focused.
const before = {};
for (const c of SPEC.cases) before[c.id] = hostOf(c.id).querySelector('input');
before['n-basic'].value = '777';
const early = hostOf('n-decimals');
early.value = '42.25';
const focused = hostOf('n-id').querySelector('input');
focused.focus();
hostOf('n-id').value = '6000'; // impl review round 1: an EARLY property on the focused control's host
const tampered = mismatch.querySelector('#mm-onclick input');
tampered.value = '4321';

const { TdNumberInput } = await import('./td-number-input.js');

describe('td-number-input SSR (number-input@1) — no JS', () => {
  it('a native type=number control submits the clean canonical value (native and element markup)', () => {
    expect(noJs.type).to.equal('number');
    expect(noJs.submit).to.equal('12990000');
    expect(noJs.elementSubmit).to.equal('12990000');
  });
});

describe('td-number-input SSR (number-input@1) — adopted in place', () => {
  for (const c of SPEC.cases) {
    it(`${c.id}: same control node (now text, formatted), marker consumed, state on the host, one FormData entry`, () => {
      const host = hostOf(c.id);
      const input = host.querySelector('input');
      expect(host instanceof TdNumberInput).to.equal(true);
      expect(input === before[c.id], 'control node kept').to.equal(true);
      expect(host.hasAttribute('data-td-ssr')).to.equal(false);
      expect(input.type).to.equal('text');
      for (const a of ['name', 'min', 'max', 'step', 'required', 'value']) expect(input.hasAttribute(a), a).to.equal(false);
      const want = c.expect;
      const value = c.id === 'n-basic' ? '777' : c.id === 'n-decimals' ? '42.25' : c.id === 'n-id' ? '6000' : want.value;
      const display = c.id === 'n-basic' ? '777' : c.id === 'n-decimals' ? '42,25' : c.id === 'n-id' ? '6.000' : want.display;
      expect(host.value).to.equal(value);
      expect(input.value).to.equal(display);
      if (want.controlId) expect(input.id).to.equal(want.controlId);
      if (want.hostId) expect(host.id).to.equal(want.hostId);
      if (want.label) expect(input.labels[0].textContent.replace(' *', '')).to.equal(want.label);
      if (want.ariaLabel) expect(input.getAttribute('aria-label')).to.equal(want.ariaLabel);
      if (want.unit) expect((input.getAttribute('aria-describedby') || '').split(' ').includes(`${host.id}-unit`)).to.equal(true);
      expect(host.required).to.equal(!!want.required);
      expect(input.disabled).to.equal(!!want.disabled);
      expect(input.readOnly).to.equal(!!want.readonly);
      if (want.error) {
        expect(host.querySelector('.td-field-error').textContent).to.equal(want.error);
        expect(input.getAttribute('aria-invalid')).to.equal('true');
      }
      const name = host.getAttribute('name');
      expect(new FormData(host.closest('form')).getAll(name)).to.deep.equal(want.disabled ? [] : [value]);
      for (const bad of c.dropped || []) expect(host.hasAttribute(bad) || input.hasAttribute(bad), bad).to.equal(false);
    });
  }

  it('no layout shift: every host keeps its box (≤ 1px)', () => {
    for (const c of SPEC.cases) {
      const r = rect(c.id);
      const r0 = boxes0[c.id];
      expect(Math.abs(r.width - r0.width) <= 1 && Math.abs(r.height - r0.height) <= 1, `${c.id}: ${r.width}x${r.height} vs ${r0.width}x${r0.height}`).to.equal(true);
    }
  });

  it('a focused control keeps the focus (node + focus + value; the caret is not promised); an early value is the focus baseline (no change on blur)', () => {
    const host = hostOf('n-id');
    expect(document.activeElement === focused).to.equal(true);
    expect(host.value).to.equal('6000');
    let changes = 0;
    host.addEventListener('change', () => { changes += 1; });
    focused.blur();
    expect(changes).to.equal(0);
  });

  it('reset → the value the server printed', () => {
    const host = hostOf('n-basic');
    host.closest('form').reset();
    expect(host.value).to.equal('');
    const full2 = hostOf('n-full');
    full2.value = '1';
    full2.closest('form').reset();
    expect(full2.value).to.equal('12990000');
  });

  it('the adopted control behaves: typing path formats, FormData stays clean', () => {
    const host = hostOf('n-full');
    const input = host.querySelector('input');
    input.value = '123456';
    input.dispatchEvent(new InputEvent('input', { bubbles: true, inputType: 'insertText', data: '6' }));
    expect(input.value).to.equal('123.456');
    expect(new FormData(host.closest('form')).get('price')).to.equal('123456');
  });
});

describe('td-number-input SSR — refused markup renders safely, value restored', () => {
  for (const id of Object.keys(MM)) {
    it(`${id}: re-rendered, nothing foreign survives`, () => {
      const host = mismatch.querySelector(`#${id}`);
      expect(host.hasAttribute('data-td-ssr')).to.equal(false);
      expect(host.querySelectorAll('input').length).to.equal(1);
      expect(host.querySelector('input').type).to.equal('text');
      expect(!!host.querySelector('[onclick], [style], b, p, input[type="hidden"]')).to.equal(false);
      expect(window.__pwned).to.equal(undefined);
    });
  }

  it('the typed value of refused markup moves to the new control', () => {
    const host = mismatch.querySelector('#mm-onclick');
    const input = host.querySelector('input');
    expect(input === tampered).to.equal(false);
    expect(host.value).to.equal('4321');
    expect(input.value).to.equal('4.321');
  });

  it('host name ≠ control name (script changed it before define) → refused; one entry under the host name', () => {
    expect(new FormData(mismatch).getAll('other')).to.deep.equal(['12990000']);
  });
});
