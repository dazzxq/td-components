/**
 * Load `html` into a fresh same-origin iframe (own custom-element registry), run `before(doc, win)` (focus, a choice…),
 * then define td-dropdown there. Resolves with the iframe window / document.
 */
async function frame(html, before) {
  // one live scenario at a time: a previous iframe keeping focus must not steal it from this one (Firefox)
  document.querySelectorAll('iframe.dd-frame').forEach((x) => x.remove());
  const f = document.createElement('iframe');
  f.className = 'dd-frame';
  f.srcdoc =`<!doctype html><html><head><link rel="stylesheet" href="/td.css"></head><body>${html}<button id="other" type="button">x</button></body></html>`;
  document.body.appendChild(f);
  await new Promise((r) => { f.onload = r; });
  const win = f.contentWindow;
  const doc = f.contentDocument;
  await new Promise((r) => { const l = doc.querySelector('link'); if (l.sheet) r(); else l.onload = r; });
  await before(doc, win);
  const s = doc.createElement('script');
  s.type = 'module';
  s.src = '/src/form/td-dropdown.js';
  doc.head.appendChild(s);
  await win.customElements.whenDefined('td-dropdown');
  return { f, win, doc };
}
