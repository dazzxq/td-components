import { expect } from '@esm-bundle/chai';
// DOM nodes are compared as booleans (`a === b`): a failing chai assertion carrying DOM nodes hangs the runner.
// NO static import of the component: <td-datetime-range> is defined LATE (dynamic import below), after the no-JS checks.

// v0.40.0 (ADR 0012, plan v0.39.0-filters-range QĐ 26 + review R1-1 / R2-4 / R2-5, M3) — td_datetime_range() /
// <td-datetime-range> hydrate, contract `datetime-range@1`, in Chromium, Firefox AND WebKit (group `engines`). The markup
// is EXACTLY what php/td.php prints for every case of test/ssr/datetime-range.fixtures.json:
// test/ssr/fixtures/datetime-range.html, generated by `node test/ssr/build-datetime-range-fixture.mjs` and kept fresh
// by test/php/td-ssr-datetime-range.test.js. Native values are edited through `.value` (dirty, like typing): typing into
// a native date / datetime-local input is engine- and locale-specific.
const link = document.createElement('link');
link.rel = 'stylesheet';
link.href = '/td.css';
document.head.appendChild(link);
await new Promise((r) => { link.onload = r; link.onerror = r; });

const SPEC = await (await fetch('/test/ssr/datetime-range.fixtures.json')).json();
const FIXTURE = await (await fetch('/test/ssr/fixtures/datetime-range.html')).text();
const TPL = document.createElement('template');
TPL.innerHTML = FIXTURE;

const root = document.createElement('div');
root.innerHTML = FIXTURE;
document.body.appendChild(root);

const formOf = (id, scope = root) => scope.querySelector(`form[data-case="${id}"]`);
const hostOf = (id, scope = root) => formOf(id, scope).querySelector('td-datetime-range');
const hostHtml = (id) => TPL.content.querySelector(`form[data-case="${id}"] > td-datetime-range`).outerHTML;
const native = (host, part) => host.querySelector(`input[data-part="${part}"]`);
const entries = (form) => [...new FormData(form).entries()].map(([k, v]) => `${k}=${v}`);
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
const display = (el) => getComputedStyle(el).display;

// Hand-written mismatches (must render safely, never adopt). Base: d-values (label, values, min / max).
const base = hostHtml('d-values');
const START_INPUT = /<input class="td-dtr__native" type="date" id="[^"]+-start"[^>]*>/.exec(base)[0];
const END_INPUT = /<input class="td-dtr__native" type="date" id="[^"]+-end"[^>]*>/.exec(base)[0];
const TRIGGER = /<button type="button" class="td-dtr__trigger"[\s\S]*?<\/button>/.exec(base)[0];
const reqBoth = hostHtml('d-req-both');
const reqStart = hostHtml('d-req-start');
const MM = {
  'mm-third-input': base.replace('</div><button', '<input type="hidden" name="range[start]" value="1999-01-01"></div><button'),
  'mm-formaction': base.replace(TRIGGER, TRIGGER.replace('<button ', '<button formaction="/evil" ')),
  'mm-two-start': base.replace(END_INPUT, START_INPUT.replace(/id="([^"]+)-start"/, 'id="$1-x"')),
  'mm-missing-end': base.replace(END_INPUT, ''),
  'mm-type': base.replace(END_INPUT, END_INPUT.replace('type="date"', 'type="text"')),
  'mm-name': base.replace(END_INPUT, END_INPUT.replace('name="range[end]"', 'name="other"')),
  'mm-trigger-inside': base.replace(TRIGGER, '').replace('</div></div>', `${TRIGGER}</div></div>`),
  'mm-onclick': base.replace(START_INPUT, START_INPUT.replace('<input ', '<input onclick="window.__dtrPwn = 1" ')),
  'mm-icon-content': base.replace('aria-hidden="true"></span></button>', 'aria-hidden="true"><img alt="" data-injected=""></span></button>'),
  'mm-schema': base.replace('datetime-range@1', 'datetime-range@2'),
  // R2-5: per-side required must agree with the host
  'mm-req-wrong-side': reqStart.replace(/(data-part="start" name="rs\[start\]") required/, '$1').replace(/(data-part="end" name="rs\[end\]")/, '$1 required'),
  'mm-req-bare-one': reqBoth.replace(/(data-part="end" name="rb\[end\]") required/, '$1'),
  'mm-req-none-input': hostHtml('d-basic').replace(/(data-part="start" name="range\[start\]")/, '$1 required'),
};
const mismatch = document.createElement('div');
const rename = (html, id) => html.replace(/id="(td-[a-z]+-\d+)"/, `id="${id}"`).replace(/td-[a-z]+-\d+(?=-)/g, id);
mismatch.innerHTML = Object.entries(MM).map(([id, html]) => `<form data-case="${id}">${rename(html, id)}</form>`).join('');
document.body.appendChild(mismatch);

// --- before the module loads (no JS) ---
const noJs = {
  fd: entries(formOf('d-values')),
  names: entries(formOf('d-names')),
  trigger: display(hostOf('d-values').querySelector('.td-dtr__trigger')),
  natives: display(hostOf('d-values').querySelector('.td-dtr__natives')),
  reqStart: [native(hostOf('d-req-start'), 'start').validity.valueMissing, native(hostOf('d-req-start'), 'end').validity.valueMissing],
  reqEnd: [native(hostOf('d-req-end'), 'start').validity.valueMissing, native(hostOf('d-req-end'), 'end').validity.valueMissing],
  reqBoth: [native(hostOf('d-req-both'), 'start').validity.valueMissing, native(hostOf('d-req-both'), 'end').validity.valueMissing],
  reqNone: formOf('d-basic').checkValidity(),
  datetime: native(hostOf('d-datetime'), 'end').type,
};
const before = {};
for (const c of SPEC.cases) before[c.id] = { host: hostOf(c.id), trigger: hostOf(c.id).querySelector('.td-dtr__trigger') };
// the user edits BOTH natives before define (dirty values), and one of them keeps the focus
native(hostOf('d-values'), 'start').value = '2026-10-02';
native(hostOf('d-values'), 'end').value = '2026-10-09';
native(hostOf('d-datetime'), 'start').value = '2026-10-01T09:15';
native(hostOf('d-datetime'), 'end').value = '';
native(hostOf('d-datetime'), 'end').focus();
// an early property wins over the live native value
native(hostOf('d-names'), 'start').value = '2026-08-01';
hostOf('d-names').start = '15/08/2026';
// mismatches: live values typed; one focused
for (const id of Object.keys(MM)) {
  const h = hostOf(id, mismatch);
  const s = h.querySelectorAll('input[data-part="start"]');
  if (s.length === 1) s[0].value = '2026-10-03';
}
const warns = [];
const origWarn = console.warn;
console.warn = (...a) => { warns.push(String(a[0])); };

await import('./td-datetime-range.js');
await wait(0);
console.warn = origWarn;

describe('v0.40.0 datetime-range@1 — no JS (php markup alone)', () => {
  it('two native inputs submit name[start] / name[end] (or start_name / end_name); trigger hidden', () => {
    expect(noJs.fd).to.deep.equal(['range[start]=2026-10-01', 'range[end]=2026-10-05']);
    expect(noJs.names).to.deep.equal(['date_from=2026-09-01', 'date_to=']);
    expect(noJs.trigger).to.equal('none');
    expect(noJs.natives).to.not.equal('none');
    expect(noJs.datetime).to.equal('datetime-local');
  });
  it('required per side (R2-5): start → only start, end → only end, both → both, none → submit empty', () => {
    expect(noJs.reqStart).to.deep.equal([true, false]);
    expect(noJs.reqEnd).to.deep.equal([false, true]);
    expect(noJs.reqBoth).to.deep.equal([true, true]);
    expect(noJs.reqNone).to.equal(true);
  });
});

describe('v0.40.0 datetime-range@1 — adopted in place', () => {
  for (const c of SPEC.cases) {
    it(`${c.id}: same host + trigger, natives gone, state = expect`, () => {
      const h = hostOf(c.id);
      expect(h === before[c.id].host).to.equal(true);
      expect(h.querySelector('.td-dtr__trigger') === before[c.id].trigger, 'trigger identity kept (adopted)').to.equal(true);
      expect(h.querySelector('.td-dtr__natives')).to.equal(null);
      expect(h.querySelectorAll('input').length).to.equal(0);
      expect(h.hasAttribute('data-td-ssr')).to.equal(false);
      const want = { ...c.expect };
      if (c.id === 'd-values') Object.assign(want, { start: '02/10/2026', end: '09/10/2026' });
      if (c.id === 'd-datetime') Object.assign(want, { start: '01/10/2026 - 09:15', end: '' });
      if (c.id === 'd-names') Object.assign(want, { start: '15/08/2026' });
      expect(h.getAttribute('start') || '').to.equal(want.start);
      expect(h.getAttribute('end') || '').to.equal(want.end);
      const fd = new FormData(formOf(c.id));
      expect([...fd.keys()]).to.deep.equal(c.expect.disabled ? [] : want.names);
      if (c.expect.error) {
        expect(h.querySelector('.td-dtr__trigger').getAttribute('aria-invalid')).to.equal('true');
        expect(h.querySelector('.td-field-error').textContent).to.equal(c.expect.error);
      }
    });
  }

  it('R1-1: live native values win; FormData holds exactly ONE start + ONE end (no native keeps a name)', () => {
    const fd = new FormData(formOf('d-values'));
    expect(fd.getAll('range[start]')).to.deep.equal(['2026-10-02']);
    expect(fd.getAll('range[end]')).to.deep.equal(['2026-10-09']);
    expect(hostOf('d-values').querySelector('.td-dtr__value').textContent).to.equal('02/10/2026 – 09/10/2026');
    const dt = new FormData(formOf('d-datetime'));
    expect([dt.get('promo[start]'), dt.get('promo[end]')]).to.deep.equal(['2026-10-01T09:15:00', '']);
  });

  it('focus on a native at define → the trigger', () => {
    expect(document.activeElement === hostOf('d-datetime').querySelector('.td-dtr__trigger')).to.equal(true);
  });

  it('required after hydrate (R2-5): valueMissing per side', () => {
    const h = (id) => hostOf(id);
    expect(h('d-basic').validity.valueMissing).to.equal(false);
    expect(h('d-req-both').validity.valueMissing).to.equal(true);
    h('d-req-both').setValue({ start: '01/10/2026' });
    expect(h('d-req-both').validity.valueMissing, 'bare: either side missing').to.equal(true);
    h('d-req-start').setValue({ end: '01/10/2026' });
    expect(h('d-req-start').validity.valueMissing).to.equal(true);
    h('d-req-start').setValue({ start: '01/10/2026' });
    expect(h('d-req-start').validity.valueMissing, 'start only: end may stay empty').to.equal(false);
    h('d-req-end').setValue({ start: '01/10/2026' });
    expect(h('d-req-end').validity.valueMissing).to.equal(true);
  });

  it('invalid PHP values / bounds were dropped (empty sides, no min)', () => {
    expect(hostOf('d-invalid').getValue()).to.deep.equal({ start: '', end: '' });
    expect(hostOf('d-invalid').hasAttribute('min')).to.equal(false);
  });

  it('XSS: the label is text; dropped attrs never reach the host', () => {
    const h = hostOf('d-attrs');
    expect(h.querySelector('.td-dtr__label img')).to.equal(null);
    expect(h.hasAttribute('onclick') || h.hasAttribute('data-td-x')).to.equal(false);
    expect(window.__dtrPwn).to.equal(undefined);
  });

  it('form reset → the server defaults (not the live values typed before define)', () => {
    formOf('d-values').reset();
    expect(hostOf('d-values').getValue()).to.deep.equal({ start: '01/10/2026', end: '05/10/2026' });
  });

  it('re-connect after a move renders again with the same state', () => {
    const h = hostOf('d-error');
    const form = formOf('d-error');
    const other = document.createElement('form');
    document.body.appendChild(other);
    other.appendChild(h);
    form.appendChild(h);
    expect(h.querySelectorAll('.td-dtr__trigger').length).to.equal(1);
    expect(h.getValue()).to.deep.equal({ start: '01/10/2026', end: '02/10/2026' });
    expect(entries(form)).to.deep.equal(['er[start]=2026-10-01', 'er[end]=2026-10-02']);
    other.remove();
  });
});

describe('v0.40.0 datetime-range@1 — refused markup (safe render)', () => {
  for (const id of Object.keys(MM)) {
    it(`${id}: rendered fresh, no stray form entry, no foreign attribute`, () => {
      const h = hostOf(id, mismatch);
      expect(h.querySelector('.td-dtr__natives')).to.equal(null);
      expect(h.querySelectorAll('input, textarea, select').length).to.equal(0);
      expect(h.querySelectorAll('button').length).to.equal(1);
      expect(h.querySelector('[onclick], [formaction], img')).to.equal(null);
      const keys = [...new FormData(formOf(id, mismatch)).keys()];
      expect(keys.every((k) => /\[(start|end)\]$|^other$/.test(k)) && keys.length <= 2, keys.join(',')).to.equal(true);
    });
  }

  it('live values are kept only from an unambiguous candidate (one input per side)', () => {
    expect(hostOf('mm-third-input', mismatch).getValue().start).to.equal('03/10/2026');
    expect(hostOf('mm-onclick', mismatch).getValue().start).to.equal('03/10/2026');
    // two inputs with data-part="start": nothing taken from either — the host attribute stays
    expect(hostOf('mm-two-start', mismatch).getValue().start).to.equal('01/10/2026');
  });

  it('the focus inside a refused host goes to the new trigger (own frame: one focus per document)', async () => {
    const frame = document.createElement('iframe');
    const html = rename(MM['mm-name'], 'fx');
    frame.srcdoc = `<!doctype html><html><head><link rel="stylesheet" href="/td.css"></head><body><form>${html}</form></body></html>`;
    document.body.appendChild(frame);
    await new Promise((r) => { frame.onload = r; });
    frame.contentWindow.focus();
    const input = frame.contentDocument.querySelector('input[data-part="start"]');
    input.focus();
    expect(frame.contentDocument.activeElement === input, 'precondition: native focused').to.equal(true);
    const sc = frame.contentDocument.createElement('script');
    sc.type = 'module';
    sc.src = '/src/form/td-datetime-range.js';
    frame.contentDocument.head.appendChild(sc);
    await frame.contentWindow.customElements.whenDefined('td-datetime-range');
    await wait(0);
    const doc = frame.contentDocument;
    const h = doc.querySelector('td-datetime-range');
    expect(h.querySelector('.td-dtr__natives')).to.equal(null);
    expect(doc.activeElement === h.querySelector('.td-dtr__trigger')).to.equal(true);
    expect(h.getValue().start).to.equal('01/10/2026');
    frame.remove();
  });

  it('no injected script ran anywhere', () => {
    expect(window.__dtrPwn).to.equal(undefined);
  });
});
