import { expect } from '@esm-bundle/chai';
// DOM nodes are compared as booleans (`a === b`): a failing chai assertion carrying DOM nodes hangs the runner.
// NO static import of the component: <td-color-picker> is defined LATE (dynamic import below), after the no-JS checks.

// v0.48.0 (ADR 0012, plan v0.48.0-color-picker QĐ 1 / 19, M2) — td_color_picker() / <td-color-picker> hydrate, contract
// `color-picker@1`, in Chromium, Firefox AND WebKit (group `engines`). The markup is EXACTLY what php/td.php prints for
// every case of test/ssr/color-picker.fixtures.json: test/ssr/fixtures/color-picker.html, generated by
// `node test/ssr/build-color-picker-fixture.mjs` and kept fresh by test/php/td-ssr-color.test.js.
const link = document.createElement('link');
link.rel = 'stylesheet';
link.href = '/td.css';
document.head.appendChild(link);
await new Promise((r) => { link.onload = r; link.onerror = r; });

const SPEC = await (await fetch('/test/ssr/color-picker.fixtures.json')).json();
const FIXTURE = await (await fetch('/test/ssr/fixtures/color-picker.html')).text();
const TPL = document.createElement('template');
TPL.innerHTML = FIXTURE;

const root = document.createElement('div');
root.innerHTML = FIXTURE;
document.body.appendChild(root);

const formOf = (id, scope = root) => scope.querySelector(`form[data-case="${id}"]`);
const hostOf = (id, scope = root) => scope.querySelector(`form[data-case="${id}"] > td-color-picker`);
const hostHtml = (id) => TPL.content.querySelector(`form[data-case="${id}"] > td-color-picker`).outerHTML;

// Hand-written mismatches (must render, never adopt).
const base = hostHtml('e-label-value');
const MM = {
  'mm-onclick': base.replace('<input ', '<input onclick="window.__pwned = 1" '),
  'mm-schema': base.replace('color-picker@1', 'color-picker@2'),
  'mm-hidden-input': base.replace('</div></div>', '</div><input type="hidden" name="c" value="#000000"></div>'),
  'mm-type-color': base.replace('type="text"', 'type="color"'),
  'mm-formaction': base.replace('<input ', '<input formaction="/evil" '),
  'mm-pattern': base.replace('pattern="#[0-9a-fA-F]{6}"', 'pattern=".*"'),
  'mm-button': base.replace('<span class="td-color__swatch" aria-hidden="true"></span>', '<button type="submit" class="td-color__trigger">x</button>'),
};
const mismatch = document.createElement('div');
const rename = (html, id) => html.replace(/id="td-c-\d+"/, `id="${id}"`).replace(/td-c-\d+-input/g, `${id}-input`);
mismatch.innerHTML = Object.entries(MM).map(([id, html]) => `<form data-case="${id}">${rename(html, id)}</form>`).join('');
document.body.appendChild(mismatch);

// --- before the module loads (no JS): the native pattern accepts ONLY #RRGGBB (QĐ 1) ---
const noJs = {};
{
  const f = formOf('n-value');
  noJs.value = new FormData(f).getAll('c');
  const input = f.querySelector('input');
  const probe = (v) => { input.value = v; return { valid: f.checkValidity(), pm: input.validity.patternMismatch, fd: new FormData(f).getAll('c') }; };
  noJs.upper = probe('#AABBCC');
  noJs.short = probe('#ABC');
  noJs.bare = probe('abc');
  noJs.bare6 = probe('aabbcc');
  noJs.word = probe('xyz');
  noJs.empty = probe('');
  input.value = '#1d4ed8';
  const req = formOf('n-required');
  noJs.required = req.checkValidity();
  noJs.swatch = getComputedStyle(f.querySelector('.td-color__swatch'));
  noJs.swatchW = noJs.swatch.width;
  noJs.inputLeft = f.querySelector('.td-color__input').getBoundingClientRect().left;
}
const before = {};
for (const c of SPEC.cases) before[c.id] = hostOf(c.id).querySelector('input');
// the swatch + text position of an element-mode field before the upgrade (no layout shift on hydrate)
const pre = hostOf('e-label-value').querySelector('input');
const preRect = pre.getBoundingClientRect();
const preText = preRect.left + parseFloat(getComputedStyle(pre).paddingLeft);
// the user typed into an adopted field and into a refused one before the upgrade
const typed = hostOf('e-id').querySelector('input');
typed.value = '#ABC';
const tampered = mismatch.querySelector('form[data-case="mm-onclick"] input');
tampered.value = '#12';
tampered.focus();
tampered.setSelectionRange(2, 2);

const { TdColorPicker } = await import('./td-color-picker.js');
await new Promise((r) => requestAnimationFrame(() => requestAnimationFrame(r)));
// read before any test moves the focus
const restored = (() => {
  const input = hostOf('mm-onclick', mismatch).querySelector('input');
  return { focused: document.activeElement === input, caret: input.selectionStart };
})();

describe('td-color-picker SSR (color-picker@1) — no JS', () => {
  it('native field submits its value; #AABBCC passes the pattern, #ABC / abc / aabbcc / xyz are blocked, empty passes', () => {
    expect(noJs.value).to.deep.equal(['#1d4ed8']);
    expect(noJs.upper).to.deep.equal({ valid: true, pm: false, fd: ['#AABBCC'] });
    for (const k of ['short', 'bare', 'bare6', 'word']) {
      expect(noJs[k].valid, k).to.equal(false);
      expect(noJs[k].pm, k).to.equal(true);
    }
    expect(noJs.empty).to.deep.equal({ valid: true, pm: false, fd: [''] });
    expect(noJs.required).to.equal(false);
  });

  it('the server swatch is a grey square of the final size (CSS only, no inline colour)', () => {
    expect(noJs.swatchW).to.equal(getComputedStyle(hostOf('e-basic').querySelector('.td-color__swatch')).width);
    expect(noJs.swatch.backgroundColor !== 'rgba(0, 0, 0, 0)').to.equal(true);
  });

  it('native (no element) forms are left alone by the module', () => {
    expect(formOf('n-basic').querySelector('td-color-picker')).to.equal(null);
    expect(formOf('n-basic').querySelector('input').getAttribute('pattern')).to.equal('#[0-9a-fA-F]{6}');
  });
});

describe('td-color-picker SSR — adopted in place (shared gate)', () => {
  for (const c of SPEC.cases) {
    it(`${c.id}: same input node, marker consumed, value on the host, one FormData entry, buttons added`, () => {
      const host = hostOf(c.id);
      const input = host.querySelector('input.td-color__input');
      expect(input === before[c.id], 'input node kept').to.equal(true);
      expect(host.hasAttribute('data-td-ssr')).to.equal(false);
      expect(host instanceof TdColorPicker).to.equal(true);
      const want = c.expect;
      if (c.id !== 'e-id') expect(host.value).to.equal(want.value);
      for (const a of ['name', 'value', 'required', 'pattern', 'title']) expect(input.hasAttribute(a), `no-JS ${a} removed`).to.equal(false);
      if (want.controlId) expect(input.id).to.equal(want.controlId);
      if (want.hostId) expect(host.id).to.equal(want.hostId);
      if (want.label) expect(input.labels[0].textContent).to.equal(want.label);
      if (want.placeholder) expect(input.getAttribute('placeholder')).to.equal(want.placeholder);
      expect(host.required).to.equal(!!want.required);
      expect(input.disabled).to.equal(!!want.disabled);
      expect(input.readOnly).to.equal(!!want.readonly);
      if (want.error) {
        expect(host.querySelector('.td-field-error').textContent).to.equal(want.error);
        expect(input.getAttribute('aria-invalid')).to.equal('true');
      }
      if (want.presets) expect(host.presets.map((p) => p.value)).to.deep.equal(want.presets);
      const entries = new FormData(host.closest('form')).getAll('c');
      expect(entries).to.deep.equal(want.disabled ? [] : [host.value]);
      const trigger = host.querySelector('.td-color__trigger');
      expect(!!trigger && trigger.querySelector(':scope > .td-color__swatch') !== null, 'swatch wrapped in the button').to.equal(true);
      expect(host.querySelectorAll('.td-color__swatch').length).to.equal(1);
      expect(host.querySelector('.td-color__clear') !== null, 'clear button added on bind').to.equal(true);
      for (const bad of c.dropped || []) expect(host.hasAttribute(bad) || input.hasAttribute(bad), bad).to.equal(false);
    });
  }

  it('no layout shift: the text starts where it started before the upgrade', () => {
    const now = pre.getBoundingClientRect();
    expect(Math.abs(now.top - preRect.top) < 0.5).to.equal(true);
    expect(Math.abs(now.height - preRect.height) < 0.5).to.equal(true);
    const text = now.left + parseFloat(getComputedStyle(pre).paddingLeft);
    expect(Math.abs(text - preText) < 1, `text start ${preText} → ${text}`).to.equal(true);
    expect(pre.closest('.td-color__box').getBoundingClientRect().height).to.equal(hostOf('e-basic').querySelector('.td-color__box').getBoundingClientRect().height);
  });

  it('the text typed before the upgrade (#ABC) is parsed by the JS (wider than the no-JS pattern) and normalised', () => {
    const host = hostOf('e-id');
    expect(host.value).to.equal('#aabbcc');
    expect(typed.value).to.equal('#aabbcc');
    expect(host.checkValidity()).to.equal(true);
    typed.focus();
    typed.value = '#123';
    typed.dispatchEvent(new InputEvent('input', { bubbles: true }));
    typed.blur();
    expect(typed.value).to.equal('#112233');
    expect(new FormData(host.closest('form')).getAll('c')).to.deep.equal(['#112233']);
  });

  it('form.reset() → the server value; swatch painted', () => {
    const host = hostOf('e-label-value');
    host.value = '#ff0000';
    host.closest('form').reset();
    expect(host.value).to.equal('#1d4ed8');
    expect(host.style.getPropertyValue('--_td-cp-color')).to.equal('#1d4ed8');
    expect(host.querySelector('.td-color__swatch').getAttribute('data-state')).to.equal('filled');
  });

  it('the popup opens from an adopted host', () => {
    const host = hostOf('e-presets');
    host.querySelector('.td-color__trigger').click();
    const panel = document.querySelector('body > .td-color-panel');
    expect(!!panel).to.equal(true);
    expect([...panel.querySelectorAll('.td-color-panel__preset')].map((b) => b.dataset.value)).to.deep.equal(['#b3261e', '#ffffff']);
    expect(!!panel.querySelector('.td-color-panel__contrast')).to.equal(true);
    host.close();
  });
});

describe('td-color-picker SSR — refused markup renders safely, typed text + focus restored', () => {
  for (const id of Object.keys(MM)) {
    it(`${id}: re-rendered, nothing foreign survives`, () => {
      const host = hostOf(id, mismatch);
      expect(host.hasAttribute('data-td-ssr')).to.equal(false);
      expect(host.querySelectorAll('input').length).to.equal(1);
      expect(host.querySelector('input').type).to.equal('text');
      expect(!!host.querySelector('[onclick], [formaction], [style], [pattern], input[type="hidden"], button[type="submit"]')).to.equal(false);
      expect(window.__pwned).to.equal(undefined);
      expect(new FormData(host.closest('form')).getAll('c').length).to.equal(1);
    });
  }

  it('the focused tampered input: text, caret and focus moved to the new input (badInput kept)', () => {
    const host = hostOf('mm-onclick', mismatch);
    const input = host.querySelector('input');
    expect(input === tampered).to.equal(false);
    expect(input.value).to.equal('#12');
    expect(restored.focused).to.equal(true);
    expect(restored.caret).to.equal(2);
    expect(host.validity.badInput).to.equal(true);
  });
});
