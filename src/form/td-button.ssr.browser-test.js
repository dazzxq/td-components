const FORWARDED = new Set(['aria-label', 'aria-pressed', 'aria-expanded', 'aria-haspopup', 'aria-controls']);
/** Control names the component owns: an `attrs` entry with one of these names is never printed in element mode. */
const OWNED = new Set(['class', 'type', 'id', 'name', 'value', 'disabled', 'aria-busy', 'aria-disabled', 'data-tooltip', 'href', 'target', 'rel', 'download']);

/** Order-independent serialisation (sorted attributes, sorted class tokens, whitespace-only text dropped). */
function serial(node, ignore = []) {
  if (node.nodeType === Node.TEXT_NODE) return node.data.trim() ? `#${node.data}` : '';
  if (node.nodeType !== Node.ELEMENT_NODE) return '';
  const attrs = [...node.attributes].filter((a) => !ignore.includes(a.name))
    .map((a) => `${a.name}=${JSON.stringify(a.name === 'class' ? a.value.split(/\s+/).filter(Boolean).sort().join(' ') : a.value)}`)
    .sort();
  return `<${node.localName} ${attrs.join(' ')}>${[...node.childNodes].map((n) => serial(n)).join('')}</${node.localName}>`;
}
const rect = (el) => { const r = el.getBoundingClientRect(); return { x: r.x + scrollX, y: r.y + scrollY, w: r.width, h: r.height }; }; // page coordinates

/** FormData of a real requestSubmit(submitter) (the native submit path). */
function submitData(form, submitter) {
  let out = null;
  const on = (e) => { e.preventDefault(); out = { entries: [...new FormData(form, e.submitter)], submitter: e.submitter }; };
  form.addEventListener('submit', on);
  try { form.requestSubmit(submitter); } finally { form.removeEventListener('submit', on); }
  return out;
}

/**
 * Synthetic click on a control: did it reach a plain (bubble-phase) listener on the control (true), or was it swallowed
 * by the component's capture listener (false)? The listener sits on the control itself (works even when a failed
 * hydrate detached it) and always cancels the activation — the test page never navigates / submits.
 */
function clickReaches(el) {
  let reached = false;
  const on = (e) => { reached = true; e.preventDefault(); };
  el.addEventListener('click', on);
  const ev = new MouseEvent('click', { bubbles: true, cancelable: true });
  try { el.dispatchEvent(ev); } finally { el.removeEventListener('click', on); }
  expect(ev.defaultPrevented, 'activation must always be cancelled').to.equal(true);
  return reached;
}

