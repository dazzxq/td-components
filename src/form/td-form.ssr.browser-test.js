/**
 * Load fixture cases into a fresh same-origin iframe (own custom-element registry), run `before(doc)` (focus, typing…),
 * then define the components there. Resolves with the iframe window / document.
 */
async function frameCase(caseIds, before) {
  const f = document.createElement('iframe');
  const forms = caseIds.map((id) => TPL.content.querySelector(`form[data-case="${id}"]`).outerHTML).join('');
  f.srcdoc = `<!doctype html><html><head><link rel="stylesheet" href="/td.css"></head><body>${forms}<button id="other" type="button">x</button></body></html>`;
  document.body.appendChild(f);
  await new Promise((r) => { f.onload = r; });
  const win = f.contentWindow;
  const doc = f.contentDocument;
  await before(doc, win);
  for (const m of ['td-input-field', 'td-toggle', 'td-checkbox']) {
    const s = doc.createElement('script');
    s.type = 'module';
    s.src = `/src/form/${m}.js`;
    doc.head.appendChild(s);
  }
  await Promise.all(Object.values(TAG).map((t) => win.customElements.whenDefined(t)));
  return { f, win, doc };
}
const customEvents = (host, win) => {
  const list = [];
  for (const t of ['input', 'change']) host.addEventListener(t, (e) => { if (e instanceof win.CustomEvent) list.push(t); });
  return list;
};

