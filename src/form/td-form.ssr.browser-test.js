/** Pass-through attribute names of a case (`attrs` / `input_attrs` on the control, minus the dropped owned names). */
function passThrough(c) {
  const o = c.args.at(-1);
  const src = c.fn === 'td_field' ? o.attrs : o.input_attrs;
  const drop = new Set(c.dropOnControl || []);
  const hints = ['autocomplete', 'inputmode', 'enterkeyhint', 'autocapitalize', 'spellcheck', 'autofocus', 'aria-label'];
  return Object.keys(src || {}).map((k) => k.toLowerCase()).filter((k) => !drop.has(k) && !(c.fn === 'td_field' && hints.includes(k)));
}

/** Ignore rule for "hydrated DOM = JS render": pass-through attributes + the kept control id of a toggle / checkbox. */
function ignoreAfter(c) {
  const pass = new Set(passThrough(c));
  return (node, name) => isControl(node) && (pass.has(name) || (c.fn !== 'td_field' && name === 'id'));
}
/** Ignore rule for "PHP markup before define = JS render": also the no-JS-only attributes of the control. */
function ignoreBefore(c) {
  const after = ignoreAfter(c);
  const o = c.args.at(-1);
  const type = o.type || 'text';
  const ssrOnly = c.fn === 'td_field'
    ? ['name', 'required', 'pattern', 'minlength', 'autofocus', ...['min', 'max', 'step'].filter((a) => !(KEEP[type] || []).includes(a)),
      ...(NEUTRAL.includes(type) ? ['type', 'inputmode'] : [])]
    : ['name', 'value', 'checked', 'required'];
  return (node, name) => after(node, name) || (isControl(node) && ssrOnly.includes(name));
}

