import { expect } from '@esm-bundle/chai';
// DOM nodes are compared as booleans (`a === b`): chai serialising DOM nodes on failure hangs the runner.
// NO static import of the component: <td-media-field> is defined LATE (dynamic import below), after the no-JS checks.

// v0.32.0 (ADR 0012, plan v0.32.0-media-picker decisions 24-25, 29, M4 hydrate / re-bind, M5) — td_media_field() /
// <td-media-field> hydrate in place, contract `media-field@1`, in Chromium, Firefox AND WebKit (group `engines`). The
// markup is EXACTLY what php/td.php prints for every case of test/ssr/media-field.fixtures.json:
// test/ssr/fixtures/media-field.html, generated by `node test/ssr/build-media-field-fixture.mjs` and kept fresh by
// test/php/td-ssr-media-field.test.js.
const link = document.createElement('link');
link.rel = 'stylesheet';
link.href = '/td.css';
document.head.appendChild(link);
await new Promise((r) => { link.onload = r; link.onerror = r; });

const SPEC = await (await fetch('/test/ssr/media-field.fixtures.json')).json();
const FIXTURE = await (await fetch('/test/ssr/fixtures/media-field.html')).text();
const TPL = document.createElement('template');
TPL.innerHTML = FIXTURE;

const root = document.createElement('div');
root.style.width = '320px'; // test page only
root.innerHTML = FIXTURE;
document.body.appendChild(root);

const formOf = (id) => root.querySelector(`form[data-case="${id}"]`);
const hostOf = (id) => formOf(id).querySelector(':scope > td-media-field');
const hostHtml = (id) => TPL.content.querySelector(`form[data-case="${id}"] > td-media-field`);
const fd = (form) => [...new FormData(form)].map(([k, v]) => [k, String(v)]);
const vis = (el) => getComputedStyle(el).visibility;

// Hand-written mismatches of the usage case (must render, never adopt) — the alt being typed + the focus must survive.
const usageHost = hostHtml('usage-full');
const usageId = usageHost.id;
const usageHtml = usageHost.outerHTML;
const MM = {
  'mm-schema': usageHtml.replace('media-field@1', 'media-field@2'),
  'mm-onerror': usageHtml.replace('<img ', '<img onerror="window.__pwned = 1" '),
  'mm-style': usageHtml.replace('<div class="td-media-field__frame"', '<div style="outline: 5px solid red" class="td-media-field__frame"'),
  'mm-extra': usageHtml.replace('<span class="td-sr-only"', '<b>thừa</b><span class="td-sr-only"'),
  'mm-hidden-foreign': usageHtml.replace('</td-media-field>', '<input type="hidden" name="steal" value="1"></td-media-field>'),
  'mm-name': usageHtml.replace(' name="og" ', ' name="other" '),
  'mm-src': usageHtml.replace(/<img class="td-media-field__img" src="[^"]*"/, '<img class="td-media-field__img" src="/test/fixtures/3.svg"'),
  'mm-crop': usageHtml.replace(/(class="td-media-field__crop" name="og\[crop\]" value=")[^"]*"/, '$1null"'),
};
const mismatch = document.createElement('form');
mismatch.innerHTML = Object.entries(MM).map(([id, html]) => html.replaceAll(usageId, id)).join('');
document.body.appendChild(mismatch);

// Images loaded before measuring (the free case's box follows its image).
await Promise.all([...root.querySelectorAll('img')].map((img) => (img.complete ? null
  : new Promise((r) => { img.onload = r; img.onerror = r; setTimeout(r, 2000); }))));

// --- before define ---
const before = {};
for (const c of SPEC.cases) {
  const host = hostOf(c.id);
  before[c.id] = {
    entries: fd(formOf(c.id)),
    open: host.querySelector('.td-media-field__open'),
    img: host.querySelector('img'),
    alt: host.querySelector('.td-media-field__alt'),
    box: host.getBoundingClientRect(),
    openVis: vis(host.querySelector('.td-media-field__open')),
    actionVis: [...host.querySelectorAll('.td-media-field__actions button')].map(vis),
    imgVis: host.querySelector('img') ? vis(host.querySelector('img')) : null,
  };
}
// typed before the module loads: adopted case keeps it (same node); refused case keeps it + the focus on the new input
const typed = hostOf('usage-full').querySelector('.td-media-field__alt');
typed.value = 'Đang gõ trước khi tải';
before['usage-full'].entries = fd(formOf('usage-full'));
const tampered = mismatch.querySelector('#mm-onerror .td-media-field__alt');
tampered.value = 'Gõ dở';
tampered.focus();

const warns = [];
const realWarn = console.warn;
console.warn = (...a) => { warns.push(a.map(String).join(' ')); };
const events = [];
for (const t of ['input', 'change']) document.addEventListener(t, (e) => { if (e.target.localName === 'td-media-field') events.push(t); }, true);

const { TdMediaField } = await import('./td-media-field.js');
console.warn = realWarn;

describe('td-media-field SSR (media-field@1) — before define', () => {
  it('open / Đổi / Gỡ buttons visibility: hidden; the preview image stays visible', () => {
    for (const c of SPEC.cases) {
      expect(before[c.id].openVis, c.id).to.equal('hidden');
      expect(before[c.id].actionVis.every((v) => v === 'hidden'), c.id).to.equal(true);
      if (before[c.id].imgVis) expect(before[c.id].imgVis, c.id).to.equal('visible');
    }
  });

  it('no-JS FormData = the component\'s shape for every case (typed alt included)', () => {
    for (const c of SPEC.cases) {
      const want = c.id === 'usage-full' ? [c.expect.entries[0], ['og[alt]', 'Đang gõ trước khi tải'], c.expect.entries[2]] : c.expect.entries;
      expect(before[c.id].entries, c.id).to.deep.equal(want);
    }
  });
});

describe('td-media-field SSR (media-field@1) — adopted in place', () => {
  for (const c of SPEC.cases) {
    it(`${c.id}: same nodes, marker consumed, FormData before == after (one set), box ± 1px, buttons visible`, () => {
      const host = hostOf(c.id);
      const b = before[c.id];
      expect(host instanceof TdMediaField).to.equal(true);
      expect(host.hasAttribute('data-td-ssr')).to.equal(false);
      expect(host.querySelector('.td-media-field__open') === b.open, 'open button kept').to.equal(true);
      expect(host.querySelector('img') === b.img, 'img kept').to.equal(true);
      expect(host.querySelector('.td-media-field__alt') === b.alt, 'alt input kept').to.equal(true);
      expect(host.querySelectorAll('input[type="hidden"]').length, 'no-JS hidden inputs removed').to.equal(0);
      if (b.alt) expect(b.alt.hasAttribute('name') || b.alt.hasAttribute('value')).to.equal(false);
      expect(fd(formOf(c.id)), 'FormData before == after').to.deep.equal(b.entries);
      expect(host.value).to.equal(c.expect.value);
      const r = host.getBoundingClientRect();
      expect(Math.abs(r.width - b.box.width) <= 1 && Math.abs(r.height - b.box.height) <= 1, `${r.width}×${r.height} vs ${b.box.width}×${b.box.height}`).to.equal(true);
      expect(vis(host.querySelector('.td-media-field__open'))).to.equal('visible');
      for (const btn of host.querySelectorAll('.td-media-field__actions button')) expect(vis(btn)).to.equal('visible');
      expect([...host.querySelectorAll('*')].some((n) => n.hasAttribute('style') || [...n.attributes].some((a) => a.name.startsWith('on')))).to.equal(false);
      if (c.expect.hostId) expect(host.id).to.equal(c.expect.hostId);
      if (c.expect.disabled) expect([...host.querySelectorAll('button, input')].every((x) => x.disabled)).to.equal(true);
      if (c.expect.required) expect(host.validity.valueMissing).to.equal(true);
      if (c.expect.error) {
        expect(host.querySelectorAll('.td-field-error').length).to.equal(1);
        expect(host.querySelector('.td-field-error').textContent).to.equal(c.expect.error);
        expect(host.querySelector('.td-media-field__open').getAttribute('aria-invalid')).to.equal('true');
      }
      if (c.expect.ratio) expect(host.querySelector('.td-media-field__ratio')?.textContent ?? `${c.expect.ratio}`).to.equal(c.expect.ratio);
      if (c.expect.noImg) expect(!!host.querySelector('img')).to.equal(false);
      for (const bad of c.dropOnHost || []) expect(host.hasAttribute(bad), bad).to.equal(false);
    });
  }

  it('the alt typed before the upgrade wins over the attribute (live native state)', () => {
    expect(hostOf('usage-full').querySelector('.td-media-field__alt').value).to.equal('Đang gõ trước khi tải');
    expect(hostOf('usage-full').selection[0].usage.altText).to.equal('Đang gõ trước khi tải');
  });

  it('crop kept byte-identical; selection carries it', () => {
    const s = hostOf('usage-full').selection[0];
    expect(s.asset).to.equal(null);
    expect(s.usage.crop).to.deep.equal({ normalized: { x: 0.1, y: 0, width: 0.5, height: 1 } });
  });

  it('usage + name[] → not submitted and warned; hydrate fires no input / change', () => {
    expect(warns.some((w) => w.includes('list[]'))).to.equal(true);
    expect(events).to.deep.equal([]);
  });

  it('XSS case: every value stays text', () => {
    const host = hostOf('xss');
    expect(!!host.querySelector('[onerror], script, b, i')).to.equal(false);
    expect(host.querySelector('.td-media-field__label').textContent).to.equal('<img src=x onerror=alert(1)>');
    expect(host.querySelector('.td-media-field__name').textContent).to.equal('<script>alert(1)</script>');
  });
});

describe('td-media-field SSR — refused markup renders safely, state restored', () => {
  for (const id of Object.keys(MM)) {
    it(`${id}: re-rendered, nothing foreign survives, one set of entries from the host`, () => {
      const host = mismatch.querySelector(`#${id}`);
      expect(host instanceof TdMediaField).to.equal(true);
      expect(host.hasAttribute('data-td-ssr')).to.equal(false);
      expect(host.querySelectorAll('input[type="hidden"]').length).to.equal(0);
      expect(!!host.querySelector('[onerror], [style], [onclick], b')).to.equal(false);
      expect(host.querySelectorAll('.td-media-field__open').length).to.equal(1);
      expect(window.__pwned).to.equal(undefined);
    });
  }

  it('FormData of the refused forms: one set per field, from the host state (no foreign entry)', () => {
    const entries = fd(mismatch);
    expect(entries.filter(([k]) => k === 'steal')).to.deep.equal([]);
    expect(entries.filter(([k]) => k === 'other[id]')).to.deep.equal([['other[id]', 'm2']]);
    expect(entries.filter(([k]) => k === 'og[id]').length).to.equal(Object.keys(MM).length - 1);
    expect(entries.filter(([k, v]) => k === 'og[crop]' && v === 'null')).to.deep.equal([]); // crop from the host attribute
  });

  it('refused markup of a focused, typed alt: value + focus move to the new input', () => {
    const host = mismatch.querySelector('#mm-onerror');
    const alt = host.querySelector('.td-media-field__alt');
    expect(alt === tampered).to.equal(false);
    expect(alt.value).to.equal('Gõ dở');
    expect(document.activeElement === alt).to.equal(true);
    expect(host.selection[0].usage.altText).to.equal('Gõ dở');
  });
});

describe('td-media-field SSR — re-bind on move / tamper while detached (review R1-8)', () => {
  it('move: same nodes, focus kept, FormData unchanged, no event', () => {
    const host = hostOf('usage-full');
    const form = formOf('usage-full');
    const nodes = [host.querySelector('.td-media-field__open'), host.querySelector('img'), host.querySelector('.td-media-field__alt')];
    const fd0 = fd(form);
    nodes[2].focus();
    const n0 = events.length;
    const wrap = document.createElement('div');
    form.appendChild(wrap);
    wrap.appendChild(host);
    const now = [host.querySelector('.td-media-field__open'), host.querySelector('img'), host.querySelector('.td-media-field__alt')];
    expect(now.every((n, i) => n === nodes[i])).to.equal(true);
    expect(document.activeElement === nodes[2]).to.equal(true);
    expect(fd(form)).to.deep.equal(fd0);
    expect(events.length).to.equal(n0);
  });

  const tamper = (id, mutate, focusSel) => {
    const host = hostOf(id);
    const form = formOf(id);
    if (focusSel) host.querySelector(focusSel).focus();
    const fd0 = fd(form);
    const value = host.value;
    const n0 = events.length;
    host.remove();
    mutate(host);
    form.appendChild(host);
    return { host, form, fd0, value, n0 };
  };

  it('onclick / style on the open button → safe render, value + focus restored, no foreign attribute', () => {
    const t = tamper('contain', (h) => {
      const b = h.querySelector('.td-media-field__open');
      b.setAttribute('onclick', 'window.__pwned = 2');
      b.setAttribute('style', 'color: red');
    }, '.td-media-field__open');
    const open = t.host.querySelector('.td-media-field__open');
    expect(open.hasAttribute('onclick') || open.hasAttribute('style')).to.equal(false);
    expect(t.host.value).to.equal(t.value);
    expect(document.activeElement === open).to.equal(true);
    expect(fd(t.form)).to.deep.equal(t.fd0);
    expect(events.length).to.equal(t.n0);
  });

  it('img src → javascript: → safe render with the live preview', () => {
    const t = tamper('ref-filled', (h) => h.querySelector('img').setAttribute('src', 'javascript:alert(1)'));
    expect(t.host.querySelector('img').getAttribute('src')).to.equal('/test/fixtures/1.svg');
    expect(fd(t.form)).to.deep.equal(t.fd0);
    expect(events.length).to.equal(t.n0);
  });

  it('injected hidden input with a foreign name → removed, one entry set', () => {
    const t = tamper('free', (h) => h.insertAdjacentHTML('beforeend', '<input type="hidden" name="steal" value="1">'));
    expect(t.host.querySelectorAll('input').length).to.equal(0);
    expect(fd(t.form)).to.deep.equal([['free', 'm4']]);
    expect(events.length).to.equal(t.n0);
  });

  it('alt input removed → rendered again with the live alt (focus on it)', () => {
    const live = hostOf('usage-empty').querySelector('.td-media-field__alt');
    live.value = 'abc';
    live.dispatchEvent(new Event('input', { bubbles: true }));
    const n1 = events.length;
    const t = tamper('usage-empty', (h) => h.querySelector('.td-media-field__alt').remove(), '.td-media-field__alt');
    const alt = t.host.querySelector('.td-media-field__alt');
    expect(alt.value).to.equal('abc');
    expect(document.activeElement === alt).to.equal(true);
    expect(fd(t.form)).to.deep.equal([['og2[id]', ''], ['og2[alt]', 'abc'], ['og2[crop]', 'null']]);
    expect(events.length).to.equal(n1);
  });
});
