import { expect } from '@esm-bundle/chai';
// DOM nodes are compared as booleans (`a === b`): chai serialising DOM nodes on failure hangs the runner.
// NO static import of the component: <td-media-gallery> is defined LATE (dynamic import below), after the no-JS checks.

// v0.43.0 (ADR 0012, ADR 0021, plan v0.43.0-media-gallery decisions 19-20, M6; acceptance 1-2) — td_media_gallery() /
// <td-media-gallery> hydrate in place, contract `media-gallery@1`, in Chromium, Firefox AND WebKit (group `engines`).
// The markup is EXACTLY what php/td.php prints for every case of test/ssr/media-gallery.fixtures.json:
// test/ssr/fixtures/media-gallery.html, generated by `node test/ssr/build-media-gallery-fixture.mjs` and kept fresh by
// test/php/td-ssr-media-gallery.test.js. FormData no-JS == after define (byte for byte), for every case.
const link = document.createElement('link');
link.rel = 'stylesheet';
link.href = '/td.css';
document.head.appendChild(link);
await new Promise((r) => { link.onload = r; link.onerror = r; });

const SPEC = await (await fetch('/test/ssr/media-gallery.fixtures.json')).json();
const FIXTURE = await (await fetch('/test/ssr/fixtures/media-gallery.html')).text();
const TPL = document.createElement('template');
TPL.innerHTML = FIXTURE;

const root = document.createElement('div');
root.style.width = '360px'; // test page only
root.innerHTML = FIXTURE;
document.body.appendChild(root);

const formOf = (id) => root.querySelector(`form[data-case="${id}"]`);
const hostOf = (id) => formOf(id).querySelector(':scope > td-media-gallery');
const hostHtml = (id) => TPL.content.querySelector(`form[data-case="${id}"] > td-media-gallery`);
const fd = (form) => [...new FormData(form)].map(([k, v]) => [k, String(v)]);
const vis = (el) => getComputedStyle(el).visibility;
const lis = (h) => [...h.querySelectorAll('.td-media-gallery__list > li')];

// Hand-written mismatches of the usage case (must render, never adopt) — the alts being typed + the focus survive.
const usageHost = hostHtml('usage');
const usageId = usageHost.id;
const usageHtml = usageHost.outerHTML;
const MM = {
  'mm-schema': usageHtml.replace('media-gallery@1', 'media-gallery@2'),
  'mm-onerror': usageHtml.replace('<img ', '<img onerror="window.__pwned = 1" '),
  'mm-style': usageHtml.replace('<li class="td-media-gallery__item"', '<li style="outline: 5px solid red" class="td-media-gallery__item"'),
  'mm-extra': usageHtml.replace('<div class="td-media-gallery__bar">', '<b>thừa</b><div class="td-media-gallery__bar">'),
  'mm-hidden-foreign': usageHtml.replace('</td-media-gallery>', '<input type="hidden" name="steal" value="1"></td-media-gallery>'),
  'mm-count': usageHtml.replace(/<li class="td-media-gallery__item"(?:(?!<\/li>)[\s\S])*<\/li>(?=<\/ul>)/, ''),
  'mm-src': usageHtml.replace(/<img class="td-media-gallery__img" src="[^"]*"/, '<img class="td-media-gallery__img" src="/test/fixtures/4.svg"'),
  'mm-crop': usageHtml.replace(/(class="td-media-gallery__crop" name="g\[0\]\[crop\]" value=")[^"]*"/, '$1null"'),
  'mm-label': usageHtml.replace('>Thêm ảnh<', '>Add photo<'),
  'mm-host-attr': usageHtml.replace('<td-media-gallery ', '<td-media-gallery contenteditable="true" '),
};
const mismatch = document.createElement('form');
mismatch.innerHTML = Object.entries(MM).map(([id, html]) => html.replaceAll(usageId, id)).join('');
document.body.appendChild(mismatch);
expect(mismatch.querySelector('#mm-count').querySelectorAll('li').length).to.equal(1);

await Promise.all([...root.querySelectorAll('img')].map((img) => (img.complete ? null
  : new Promise((r) => { img.onload = r; img.onerror = r; setTimeout(r, 2000); }))));

// --- before define ---
const before = {};
for (const c of SPEC.cases) {
  const host = hostOf(c.id);
  before[c.id] = {
    entries: fd(formOf(c.id)),
    lis: lis(host),
    imgs: [...host.querySelectorAll('img')],
    alts: [...host.querySelectorAll('.td-media-gallery__alt')],
    add: host.querySelector('.td-media-gallery__add'),
    box: host.getBoundingClientRect(),
    buttonsVis: [...host.querySelectorAll('button')].map(vis),
  };
}
// typed before the module loads: adopted case keeps it (same node); refused case keeps it + the focus on the new input
const typed = hostOf('usage').querySelectorAll('.td-media-gallery__alt')[1];
typed.value = 'Đang gõ trước khi tải';
before.usage.entries = fd(formOf('usage'));
const tampered = mismatch.querySelector('#mm-onerror').querySelectorAll('.td-media-gallery__alt')[1];
tampered.value = 'Gõ dở';
tampered.focus();

const warns = [];
const realWarn = console.warn;
console.warn = (...a) => { warns.push(a.map(String).join(' ')); };
const events = [];
for (const t of ['input', 'change']) document.addEventListener(t, (e) => { if (e.target.localName === 'td-media-gallery') events.push(t); }, true);

const { TdMediaGallery } = await import('./td-media-gallery.js');
console.warn = realWarn;
const focusedAfterDefine = document.activeElement; // later tests move the focus (Gỡ clicks)

describe('td-media-gallery SSR (media-gallery@1) — before define', () => {
  it('every button (handle, Cắt, Gỡ, Add) is visibility: hidden — no dead control; images visible', () => {
    for (const c of SPEC.cases) {
      expect(before[c.id].buttonsVis.every((v) => v === 'hidden'), c.id).to.equal(true);
      for (const img of before[c.id].imgs) expect(vis(img), c.id).to.equal('visible');
    }
  });

  it('no-JS FormData = expect.entries for every case (typed alt included); overflow / broken / disabled: none', () => {
    for (const c of SPEC.cases) {
      const want = c.id === 'usage' ? c.expect.entries.map(([k, v]) => [k, k === 'g[1][alt]' ? 'Đang gõ trước khi tải' : v]) : c.expect.entries;
      expect(before[c.id].entries, c.id).to.deep.equal(want);
    }
  });
});

describe('td-media-gallery SSR (media-gallery@1) — adopted in place', () => {
  for (const c of SPEC.cases) {
    it(`${c.id}: same nodes, marker consumed, FormData before == after, box ± 1px, buttons visible`, () => {
      const host = hostOf(c.id);
      const b = before[c.id];
      expect(host instanceof TdMediaGallery).to.equal(true);
      expect(host.hasAttribute('data-td-ssr')).to.equal(false);
      expect(lis(host).length).to.equal(b.lis.length);
      expect(lis(host).every((li, i) => li === b.lis[i]), 'tiles kept').to.equal(true);
      expect([...host.querySelectorAll('img')].every((n, i) => n === b.imgs[i]), 'images kept').to.equal(true);
      expect([...host.querySelectorAll('.td-media-gallery__alt')].every((n, i) => n === b.alts[i]), 'alts kept').to.equal(true);
      expect(host.querySelector('.td-media-gallery__add') === b.add, 'Add kept').to.equal(true);
      expect(host.querySelectorAll('input[type="hidden"]').length, 'no-JS inputs removed').to.equal(0);
      for (const a of b.alts) expect(a.hasAttribute('name') || a.hasAttribute('value')).to.equal(false);
      expect(fd(formOf(c.id)), 'FormData before == after').to.deep.equal(b.entries);
      if (c.expect.state !== 'broken') expect(host.value).to.deep.equal(c.expect.value);
      const r = host.getBoundingClientRect();
      expect(Math.abs(r.width - b.box.width) <= 1 && Math.abs(r.height - b.box.height) <= 1, `${r.width}×${r.height} vs ${b.box.width}×${b.box.height}`).to.equal(true);
      for (const btn of host.querySelectorAll('button')) {
        if (!btn.hidden) expect(vis(btn), c.id).to.equal('visible');
      }
      expect([...host.querySelectorAll('*')].some((n) => n.hasAttribute('style') || [...n.attributes].some((a) => a.name.startsWith('on')))).to.equal(false);
    });
  }

  it('the alt typed before the upgrade wins over the attribute (live native state)', () => {
    const host = hostOf('usage');
    expect(host.querySelectorAll('.td-media-gallery__alt')[1].value).to.equal('Đang gõ trước khi tải');
    expect(host.selection[1].usage.altText).to.equal('Đang gõ trước khi tải');
  });

  it('usage: crop / focal kept byte-identical; Cắt shown for images with src; cover badge on the first tile', () => {
    const host = hostOf('usage');
    expect(host.selection[0].usage.crop).to.deep.equal({ normalized: { x: 0.1, y: 0, width: 0.5, height: 1 } });
    expect(host.selection[0].usage.focalPoint).to.deep.equal({ x: 0.25, y: 0.5 });
    expect(lis(host).map((li) => li.querySelector('.td-media-gallery__crop-btn').hidden)).to.deep.equal([false, false]);
    expect(host.querySelectorAll('.td-media-gallery__cover').length).to.equal(1);
  });

  it('overflow: kept, rangeOverflow, nothing submitted; Gỡ back to max → FormData', () => {
    const host = hostOf('overflow');
    expect(host.validity.rangeOverflow).to.equal(true);
    expect(fd(formOf('overflow'))).to.deep.equal([]);
    lis(host)[0].querySelector('.td-media-gallery__remove').click();
    lis(host)[0].querySelector('.td-media-gallery__remove').click();
    expect(fd(formOf('overflow')).filter(([k]) => k.endsWith('[id]'))).to.deep.equal([['o[0][id]', 'm3'], ['o[1][id]', 'm4']]);
    events.length = 0;
  });

  it('broken (duplicate ids, name ending []): adopted as the broken state, nothing submitted, warned', () => {
    for (const id of ['broken-dup', 'broken-name']) {
      expect(hostOf(id).querySelector('.td-media-gallery__broken').textContent, id).to.equal('Không đọc được danh sách ảnh');
      expect(fd(formOf(id)), id).to.deep.equal([]);
    }
    expect(warns.some((w) => w.includes('items attribute was rejected (item)'))).to.equal(true);
    expect(warns.some((w) => w.includes('name ending in []'))).to.equal(true);
  });

  it('hydrate fires no input / change; XSS case: every value stays text', () => {
    expect(events).to.deep.equal([]);
    const host = hostOf('xss');
    expect(!!host.querySelector('[onerror], script, b, i')).to.equal(false);
    expect(host.querySelector('.td-media-gallery__label').textContent).to.equal('<b>nhãn</b>');
    expect(host.querySelector('.td-media-gallery__alt').value).to.equal('<script>alert(1)</script>');
  });
});

describe('td-media-gallery SSR — refused markup renders safely, state restored', () => {
  for (const id of Object.keys(MM)) {
    it(`${id}: re-rendered, nothing foreign survives, one set of entries from the host`, () => {
      const host = mismatch.querySelector(`#${id}`);
      expect(host instanceof TdMediaGallery).to.equal(true);
      expect(host.hasAttribute('data-td-ssr')).to.equal(false);
      expect(host.querySelectorAll('input[type="hidden"]').length).to.equal(0);
      expect(!!host.querySelector('[onerror], [style], [onclick], b')).to.equal(false);
      expect(lis(host).length).to.equal(2, 'tiles from the items attribute');
      expect(window.__pwned).to.equal(undefined);
    });
  }

  it('FormData of the refused forms: one set per gallery from the host state (no foreign entry, crop from items)', () => {
    const entries = fd(mismatch);
    expect(entries.filter(([k]) => k === 'steal')).to.deep.equal([]);
    expect(entries.filter(([k]) => k === 'g[0][id]').length).to.equal(Object.keys(MM).length);
    expect(entries.filter(([k, v]) => k === 'g[0][crop]' && v === 'null')).to.deep.equal([]);
  });

  it('a focused, typed alt of refused markup: value + focus move to the new input of the SAME item', () => {
    const host = mismatch.querySelector('#mm-onerror');
    const alt = host.querySelectorAll('.td-media-gallery__alt')[1];
    expect(alt === tampered).to.equal(false);
    expect(alt.value).to.equal('Gõ dở');
    expect(focusedAfterDefine === alt).to.equal(true);
    expect(host.selection[1].usage.altText).to.equal('Gõ dở');
  });
});

describe('td-media-gallery SSR — re-bind on move / tamper while detached', () => {
  it('move: same nodes, focus kept, FormData unchanged, no event; sorting still works', () => {
    const host = hostOf('ref');
    const form = formOf('ref');
    const nodes = lis(host);
    const h = nodes[0].querySelector('.td-media-gallery__handle');
    h.focus();
    const fd0 = fd(form);
    const n0 = events.length;
    const wrap = document.createElement('div');
    form.appendChild(wrap);
    wrap.appendChild(host);
    expect(lis(host).every((n, i) => n === nodes[i])).to.equal(true);
    expect(document.activeElement === h).to.equal(true);
    expect(fd(form)).to.deep.equal(fd0);
    expect(events.length).to.equal(n0);
    h.click();
    nodes[2].querySelector('.td-media-gallery__handle').click();
    expect(host.value).to.deep.equal(['m2', 'm3', 'm1']);
  });

  it('img src → javascript: while detached → safe render with the live preview, value kept', () => {
    const host = hostOf('full');
    const form = formOf('full');
    const fd0 = fd(form);
    host.remove();
    host.querySelector('img').setAttribute('src', 'javascript:alert(1)');
    form.appendChild(host);
    expect(host.querySelector('img').getAttribute('src')).to.equal('/test/fixtures/1.svg');
    expect(fd(form)).to.deep.equal(fd0);
  });

  it('injected hidden input while detached → removed, one entry set', () => {
    const host = hostOf('kinds');
    const form = formOf('kinds');
    host.remove();
    host.insertAdjacentHTML('beforeend', '<input type="hidden" name="steal" value="1">');
    form.appendChild(host);
    expect(host.querySelectorAll('input').length).to.equal(0);
    expect(fd(form)).to.deep.equal([['m[]', 'm14'], ['m[]', 'm11'], ['m[]', 'm9']]);
  });
});
