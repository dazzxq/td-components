import { expect } from '@esm-bundle/chai';
// DOM nodes are compared as booleans (`a === b`): a failing chai assertion carrying DOM nodes as actual / expected
// makes the runner serialise the whole node graph (hangs the run instead of reporting the failure).
// NO static import of the component: <td-otp-input> is defined LATE (dynamic import below), after the no-JS checks.

// v0.27.0 (ADR 0012, plan v0.27.0-dsuite-p0a §B) — td_otp_input() element mode / <td-otp-input> hydrate in place,
// contract `otp-input@1`. Runs in Chromium, Firefox AND WebKit (web-test-runner group `engines`; the v0.25/v0.26 `ssr`
// group is kept as it was — its iframe focus scenarios must not share a Firefox instance with these top-level ones). The markup is EXACTLY what
// php/td.php prints for every case of test/ssr/otp.fixtures.json: test/ssr/fixtures/otp.html, generated by
// `node test/ssr/build-otp-copy-fixture.mjs` and kept fresh by test/php/td-ssr-otp-copy.test.js.
const link = document.createElement('link');
link.rel = 'stylesheet';
link.href = '/td.css';
document.head.appendChild(link);
await new Promise((r) => { link.onload = r; link.onerror = r; });

const SPEC = await (await fetch('/test/ssr/otp.fixtures.json')).json();
const FIXTURE = await (await fetch('/test/ssr/fixtures/otp.html')).text();
const TPL = document.createElement('template');
TPL.innerHTML = FIXTURE;

const root = document.createElement('div');
// The native n-full case carries `autofocus` (checked by the PHP test): WebKit would move the focus there on a later
// frame, away from the focus scenario below — inserted without it.
root.innerHTML = FIXTURE.replace(/ autofocus(?=[ >])/g, '');
document.body.appendChild(root);

const hostOf = (id) => root.querySelector(`form[data-case="${id}"] > td-otp-input`);
const hostHtml = (id) => TPL.content.querySelector(`form[data-case="${id}"] > td-otp-input`).outerHTML;

// Hand-written mismatches (must render, never adopt) — the state of the old control must survive.
const basic = hostHtml('o-basic');
const MM = {
  'mm-schema': basic.replace('otp-input@1', 'otp-input@2'),
  'mm-onclick': basic.replace('<input ', '<input onclick="window.__pwned = 1" '),
  'mm-style': basic.replace('<span class="td-otp__cells"', '<span style="color: red" class="td-otp__cells"'),
  'mm-cells': basic.replace('<span class="td-otp__cell"></span>', ''),
  'mm-extra': basic.replace('<div class="td-otp__box">', '<div class="td-otp__box"><b>thừa</b>'),
  'mm-type': basic.replace('type="text"', 'type="password"'),
  'mm-hidden-input': basic.replace('</div></div>', '</div><input type="hidden" name="otp_code" value="x"></div>'),
  'mm-name': basic.replace(' name="otp_code"><div', ' name="other"><div'),
};
const mismatch = document.createElement('form');
mismatch.innerHTML = Object.entries(MM).map(([id, html]) => html.replace(/id="td-otp_code-1"/, `id="${id}"`)
  .replace(/id="td-otp_code-1-input"/, `id="${id}-input"`).replace(/for="td-otp_code-1-input"/, `for="${id}-input"`)).join('');
document.body.appendChild(mismatch);

// No-JS: the element-mode field shows the native input (cells hidden); a native field too.
const box0 = hostOf('o-basic').querySelector('.td-otp__box').getBoundingClientRect();
const noJs = {
  cells: getComputedStyle(hostOf('o-basic').querySelector('.td-otp__cells')).display,
  input: getComputedStyle(hostOf('o-basic').querySelector('input')).color,
  native: getComputedStyle(root.querySelector('form.ssr-native input')).display,
};

// State typed before the module loads: an adopted case keeps value + selection (same node); a refused one keeps value,
// selection AND focus on the new control.
const before = {};
for (const c of SPEC.cases) before[c.id] = hostOf(c.id).querySelector('input');
const pre = hostOf('o-label-required').querySelector('input');
pre.value = '12';
pre.setSelectionRange(1, 1);
const tampered = mismatch.querySelector('#mm-onclick input');
tampered.value = '987';
tampered.focus();
tampered.setSelectionRange(2, 2);

const { TdOtpInput } = await import('./td-otp-input.js');

describe('td-otp-input SSR (otp-input@1) — no JS', () => {
  it('cells hidden, the native input visible (element mode and native mode)', () => {
    expect(noJs.cells).to.equal('none');
    expect(noJs.native).to.not.equal('none');
    expect(noJs.input).to.not.equal('rgba(0, 0, 0, 0)');
  });
});

describe('td-otp-input SSR (otp-input@1) — adopted in place', () => {
  for (const c of SPEC.cases) {
    it(`${c.id}: same input node, marker consumed, state on the host, one FormData entry`, () => {
      const host = hostOf(c.id);
      const input = host.querySelector('input');
      expect(input === before[c.id], 'input node kept').to.equal(true);
      expect(host.hasAttribute('data-td-ssr')).to.equal(false);
      expect(host instanceof TdOtpInput).to.equal(true);
      const want = c.expect;
      const value = c.id === 'o-label-required' ? '12' : want.value;
      expect(host.value).to.equal(value);
      expect(input.hasAttribute('name'), 'no-JS name removed').to.equal(false);
      expect(input.hasAttribute('maxlength') || input.hasAttribute('pattern') || input.hasAttribute('required')).to.equal(false);
      if (want.controlId) expect(input.id).to.equal(want.controlId);
      if (want.hostId) expect(host.id).to.equal(want.hostId);
      if (want.label) expect(input.labels[0].textContent).to.equal(want.label);
      if (want.ariaLabel) expect(input.getAttribute('aria-label')).to.equal(want.ariaLabel);
      expect(host.required).to.equal(!!want.required);
      expect(input.disabled).to.equal(!!want.disabled);
      expect(input.readOnly).to.equal(!!want.readonly);
      if (want.error) {
        expect(host.querySelector('.td-field-error').textContent).to.equal(want.error);
        expect(input.getAttribute('aria-invalid')).to.equal('true');
      }
      const form = host.closest('form');
      const name = host.getAttribute('name');
      const entries = new FormData(form).getAll(name);
      expect(entries).to.deep.equal(want.disabled ? [] : [value]);
      const shown = [...host.querySelectorAll('.td-otp__cell')].map((x) => x.textContent).join('');
      expect(shown).to.equal(value);
      for (const bad of c.dropped || []) expect(host.hasAttribute(bad) || input.hasAttribute(bad), bad).to.equal(false);
      if (c.dropped) expect(host.getAttribute('name')).to.equal('code');
    });
  }

  it('selection typed before the upgrade is kept', () => {
    expect(pre.selectionStart).to.equal(1);
    expect(pre.selectionEnd).to.equal(1);
  });

  it('no layout shift: the box keeps its size', () => {
    const r = hostOf('o-basic').querySelector('.td-otp__box').getBoundingClientRect();
    expect(Math.abs(r.width - box0.width) <= 1, `${r.width} vs ${box0.width}`).to.equal(true);
    expect(Math.abs(r.height - box0.height) <= 1, `${r.height} vs ${box0.height}`).to.equal(true);
  });
});

describe('td-otp-input SSR — refused markup renders safely, state restored', () => {
  for (const id of Object.keys(MM)) {
    it(`${id}: re-rendered (input replaced), nothing foreign survives`, () => {
      const host = mismatch.querySelector(`#${id}`);
      expect(host.hasAttribute('data-td-ssr')).to.equal(false);
      expect(host.querySelectorAll('input').length).to.equal(1);
      expect(host.querySelectorAll('.td-otp__cell').length).to.equal(6);
      expect(!!host.querySelector('[onclick], [style], b, input[type="hidden"], input[type="password"]')).to.equal(false);
      expect(window.__pwned).to.equal(undefined);
    });
  }

  it('the focused, typed control of refused markup: value, selection and focus move to the new input', () => {
    const host = mismatch.querySelector('#mm-onclick');
    const input = host.querySelector('input');
    expect(input === tampered).to.equal(false);
    expect(host.value).to.equal('987');
    expect(document.activeElement === input).to.equal(true);
    expect(input.selectionStart).to.equal(2);
  });

  it('host name ≠ control name (script changed it before define) → refused', () => {
    const host = mismatch.querySelector('#mm-name');
    expect(host.querySelector('input').hasAttribute('onclick')).to.equal(false);
    expect(new FormData(mismatch).getAll('other')).to.deep.equal(['']);
  });
});
