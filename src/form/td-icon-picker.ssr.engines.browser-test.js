import { expect } from '@esm-bundle/chai';
// DOM nodes are compared as booleans (`a === b`): a failing chai assertion carrying DOM nodes hangs the runner.
// NO static import of the component: <td-icon-picker> is defined LATE (dynamic import below), after the no-JS checks.

// v0.94.0 (ADR 0012, plan v0.94.0-icons-picker §7, §9.3) — td_icon_picker() / <td-icon-picker> hydrate, contract
// `icon-picker@1`, in Chromium, Firefox AND WebKit (group `engines`). The markup is EXACTLY what php/td.php prints for
// every case of test/ssr/icon-picker.fixtures.json: test/ssr/fixtures/icon-picker.html, generated by
// `node test/ssr/build-icon-picker-fixture.mjs` and kept fresh by test/php/td-ssr-icon-picker.test.js.
const link = document.createElement('link');
link.rel = 'stylesheet';
link.href = '/td.css';
document.head.appendChild(link);
await new Promise((r) => { link.onload = r; link.onerror = r; });

const SPEC = await (await fetch('/test/ssr/icon-picker.fixtures.json')).json();
const FIXTURE = await (await fetch('/test/ssr/fixtures/icon-picker.html')).text();
const TPL = document.createElement('template');
TPL.innerHTML = FIXTURE;

const root = document.createElement('div');
root.innerHTML = FIXTURE;
document.body.appendChild(root);

const formOf = (id, scope = root) => scope.querySelector(`form[data-case="${id}"]`);
const hostOf = (id, scope = root) => scope.querySelector(`form[data-case="${id}"] > td-icon-picker`);
const hostHtml = (id) => TPL.content.querySelector(`form[data-case="${id}"] > td-icon-picker`).outerHTML;
const trig = (h) => h.querySelector('.td-icon-picker__trigger');

// Hand-written mismatches (must render, never adopt).
const base = hostHtml('value');
const MM = {
  'mm-onclick': base.replace('<button type="button" class="td-icon-picker__trigger"', '<button type="button" onclick="window.__pwned = 1" class="td-icon-picker__trigger"'),
  'mm-schema': base.replace('icon-picker@1', 'icon-picker@2'),
  'mm-submit': base.replace('<button type="button" class="td-icon-picker__trigger"', '<button type="submit" class="td-icon-picker__trigger"'),
  'mm-hidden-value': base.replace('name="icon" value="trash">', 'name="icon" value="home">'),
  'mm-hidden-name': base.replace('class="td-icon-picker__native" name="icon"', 'class="td-icon-picker__native" name="other"'),
  'mm-hidden-extra': base.replace('</div></td-icon-picker>', '<input type="hidden" name="icon" value="x"></div></td-icon-picker>'),
  'mm-formaction': base.replace('class="td-icon-picker__native"', 'class="td-icon-picker__native" formaction="/evil"'),
  'mm-text': base.replace('data-state="value">trash</span>', 'data-state="value"><img src=x>trash</span>'),
  'mm-glyph': base.replace('data-icon="trash"', 'data-icon="home"'),
};
const mismatch = document.createElement('div');
const rename = (html, id) => html.replace(/td-icon-\d+/g, id);
mismatch.innerHTML = Object.entries(MM).map(([id, html]) => `<form data-case="${id}">${rename(html, id)}</form>`).join('');
document.body.appendChild(mismatch);

// --- before the module loads (no JS): the hidden input submits the value ---
const noJs = {};
noJs.value = new FormData(formOf('value')).getAll('icon');
noJs.alias = new FormData(formOf('alias')).getAll('icon');
noJs.disabled = new FormData(formOf('disabled')).getAll('icon');
noJs.readonly = new FormData(formOf('readonly')).getAll('icon');
noJs.basic = new FormData(formOf('basic')).getAll('icon');
const before = {};
for (const c of SPEC.cases) before[c.id] = { trigger: trig(hostOf(c.id)), box: hostOf(c.id).querySelector('.td-icon-picker__box'), rect: trig(hostOf(c.id)).getBoundingClientRect(), form: formOf(c.id).getBoundingClientRect().top };
// focus on an adopted trigger and on a refused one before the upgrade
trig(hostOf('id')).focus();
const focusedBefore = document.activeElement === trig(hostOf('id'));

const { TdIconPicker } = await import('./td-icon-picker.js');
await new Promise((r) => requestAnimationFrame(() => requestAnimationFrame(r)));
const focusKept = document.activeElement === trig(hostOf('id'));

describe('td-icon-picker SSR (icon-picker@1) — no JS', () => {
  it('the hidden input submits name / value; disabled → nothing; readonly → the value', () => {
    expect(noJs.value).to.deep.equal(['trash']);
    expect(noJs.alias).to.deep.equal(['close']);
    expect(noJs.disabled).to.deep.equal([]);
    expect(noJs.readonly).to.deep.equal(['home']);
    expect(noJs.basic).to.deep.equal(['']);
  });
});

describe('td-icon-picker SSR (icon-picker@1) — hydrate in place', () => {
  for (const c of SPEC.cases) {
    it(`${c.id}: adopted (same trigger + box), marker gone, hidden input removed, state as expected`, () => {
      const h = hostOf(c.id);
      expect(h instanceof TdIconPicker).to.equal(true);
      expect(h.hasAttribute('data-td-ssr')).to.equal(false);
      expect(trig(h) === before[c.id].trigger).to.equal(true);
      expect(h.querySelector('.td-icon-picker__box') === before[c.id].box).to.equal(true);
      expect(h.querySelector('.td-icon-picker__native')).to.equal(null);
      expect(h.value).to.equal(c.expect.value);
      const text = h.querySelector('.td-icon-picker__text');
      expect(text.getAttribute('data-state')).to.equal(c.expect.state);
      if (c.expect.text) expect(text.textContent).to.equal(c.expect.text);
      if ('clear' in c.expect) expect(h.querySelector('.td-icon-picker__clear').hidden).to.equal(!c.expect.clear);
      if (c.expect.label) expect(h.querySelector('.td-icon-picker__label').textContent).to.equal(c.expect.label);
      if (c.expect.name) expect(h.querySelector('.td-sr-only').textContent).to.equal(c.expect.name);
      if (c.expect.suggestions) expect(h.suggestions).to.deep.equal(c.expect.suggestions);
      if (c.expect.icons) expect(h.icons).to.deep.equal(c.expect.icons);
      const r = trig(h).getBoundingClientRect();
      const top = r.top - formOf(c.id).getBoundingClientRect().top - (before[c.id].rect.top - before[c.id].form); // page scroll aside
      expect(`${Math.round(top)}/${Math.round(r.height - before[c.id].rect.height)}`).to.equal('0/0');
    });
  }

  it('FormData: exactly ONE entry after the upgrade (ElementInternals), none for disabled', () => {
    expect(new FormData(formOf('value')).getAll('icon')).to.deep.equal(['trash']);
    expect(new FormData(formOf('alias')).getAll('icon')).to.deep.equal(['close']);
    expect(new FormData(formOf('readonly')).getAll('icon')).to.deep.equal(['home']);
    expect(new FormData(formOf('disabled')).getAll('icon')).to.deep.equal([]);
    expect(new FormData(formOf('unknown')).getAll('icon')).to.deep.equal(['site-later']);
  });

  it('focus on the trigger is kept through the upgrade', () => {
    expect(focusedBefore).to.equal(true);
    expect(focusKept).to.equal(true);
  });

  it('required + error: valueMissing, aria-invalid / errormessage on the trigger, the error note kept', () => {
    const h = hostOf('required-error');
    expect(h.checkValidity()).to.equal(false);
    expect(trig(h).getAttribute('aria-invalid')).to.equal('true');
    expect(trig(h).getAttribute('aria-errormessage')).to.equal(`${h.id}-error`);
    expect(h.querySelectorAll('.td-field-error').length).to.equal(1);
    expect(h.querySelector('.td-field-error').textContent).to.equal('Chọn một icon');
  });

  it('the adopted field works: open, pick → value + one change', async () => {
    const h = hostOf('basic');
    let changes = 0;
    h.addEventListener('change', () => { changes += 1; });
    h.open();
    const p = document.querySelector('body > .td-icon-picker-panel');
    expect(!!p).to.equal(true);
    p.querySelector('.td-icon-picker-panel__cell[data-icon="home"]').click();
    expect(h.value).to.equal('home');
    expect(changes).to.equal(1);
    expect(new FormData(formOf('basic')).getAll('icon')).to.deep.equal(['home']);
  });

  it('re-connect: re-binds in place (same trigger)', async () => {
    const h = hostOf('helper');
    const t = trig(h);
    const f = h.parentElement;
    h.remove();
    f.appendChild(h);
    expect(trig(h) === t).to.equal(true);
    expect(h.querySelector('.td-icon-picker__native')).to.equal(null);
  });
});

describe('td-icon-picker SSR — mismatched markup is rendered fresh, never adopted', () => {
  for (const id of Object.keys(MM)) {
    it(`${id}: safe render (no foreign attribute / node survives), one form entry`, () => {
      const f = mismatch.querySelector(`form[data-case="${id}"]`);
      const h = f.querySelector('td-icon-picker');
      expect(h instanceof TdIconPicker).to.equal(true);
      expect(h.hasAttribute('data-td-ssr')).to.equal(false);
      expect(h.querySelector('[onclick], [formaction], img, button[type="submit"], input')).to.equal(null);
      expect(h.querySelectorAll('.td-icon-picker').length).to.equal(1);
      expect(trig(h).getAttribute('type')).to.equal('button');
      expect(new FormData(f).getAll('icon').length).to.equal(1);
    });
  }

  it('the refused tamper never ran / reached the value', () => {
    expect(window.__pwned).to.equal(undefined);
    const h = mismatch.querySelector('form[data-case="mm-hidden-value"] td-icon-picker');
    expect(h.value).to.equal('trash'); // the host attribute, not the tampered input
    expect(mismatch.querySelector('form[data-case="mm-glyph"] td-icon-picker .td-icon-picker__glyph svg').getAttribute('data-icon')).to.equal('trash');
  });
});
