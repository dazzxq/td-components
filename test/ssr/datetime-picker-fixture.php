/**
 * v0.56.0 — HTML fixture of src/form/td-datetime-picker.ssr.engines.browser-test.js: every case of
 * test/ssr/datetime-picker.fixtures.json rendered by td_datetime_picker() / td_date(), each inside its own
 * `<form class="ssr-case" data-case="…">`. Regenerate with `node test/ssr/build-datetime-picker-fixture.mjs`
