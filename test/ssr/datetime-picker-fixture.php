        set_error_handler(static fn (int $no): bool => $no === E_USER_WARNING);
    }
    $html = $fn(...$case['args']);
    if (!empty($case['quiet'])) {
        restore_error_handler();
    }
    echo '<form class="ssr-case" data-case="', Td::e($case['id']), '" action="/__ssr-submit" method="post">', $html, "</form>\n";
}
