#!/usr/bin/env node
/**
 * Generate from the authored icon sources (plain ESM for browsers without JSON-module support; PHP adapters read the
 * JSON directly):
 *   src/icons/icons.json         → src/icons/registry.js       (geometry + aliases)
 *   src/icons/icons-search.json  → src/icons/icons-search.js   (v0.94.0: search metadata, loaded lazily by td-icon-picker)
 *
 *   node scripts/build-icons.mjs                → write both
 *   node scripts/build-icons.mjs --check        → exit 1 if either is stale (each stale file is named)
 *   node scripts/build-icons.mjs --root <dir>   → another package root (tests)
 *
 * Fails the build when: an icon has not exactly one of `lucide` (upstream name) / `"source": "td"` (owner-drawn,
 * ADR 0039); an alias is bad; the search metadata keys are not exactly the icon names (missing, extra, alias); an entry
 * breaks the rules of src/icons/icon-search-schema.js. Generated files are read / written through scripts/safe-file.mjs
 * (never through a symbolic link).
 */
import { readFileSync, realpathSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve } from 'node:path';
import { validateSearchEntry } from '../src/icons/icon-search-schema.js';
import { readGenerated, writeGenerated } from './safe-file.mjs';

const NAME_RE = /^[a-z][a-z0-9-]{0,63}$/;
const SEARCH_SCHEMA = 'td-icons-search/1';

/**
 * Build the two generated files from the parsed sources. Throws an Error naming the first problem.
 * @param {any} json parsed icons.json
 * @param {any} search parsed icons-search.json
 * @returns {{ registry: string, search: string, icons: number, aliases: number }}
 */
export function buildIconOutputs(json, search) {
  if (!json || typeof json !== 'object' || !json.icons || typeof json.icons !== 'object') {
    throw new Error('icons.json: "icons" must be an object');
  }
  const icons = {};
  for (const [name, def] of Object.entries(json.icons)) {
    if (!NAME_RE.test(name)) throw new Error(`icons.json: invalid icon name "${name}"`);
    // v0.94.0 (ADR 0039): exactly one origin — Lucide (upstream name) or owner-drawn td artwork.
    const lucide = typeof def?.lucide === 'string' && def.lucide !== '';
    const hasSource = Object.hasOwn(def ?? {}, 'source');
    if (hasSource && def.source !== 'td') throw new Error(`icons.json: "${name}" has source "${def.source}" (only "td")`);
    if (lucide === hasSource) {
      throw new Error(`icons.json: "${name}" must have exactly one of "lucide" (upstream name) or "source": "td"`);
    }
    if (Object.hasOwn(def, 'lucide') && !lucide) throw new Error(`icons.json: "${name}" has an empty "lucide"`);
    icons[name] = { viewBox: def.viewBox, paint: def.paint, nodes: def.nodes };
  }
  // Aliases (v0.18.0): alternative name → core icon name. Must be a valid icon name, not shadow a core icon, and point
  // at an existing core icon (no chains) — a bad entry fails the build instead of shipping a dead alias.
  const aliases = {};
  for (const [alias, target] of Object.entries(json.aliases ?? {})) {
    if (!NAME_RE.test(alias)) throw new Error(`icons.json aliases: invalid alias name "${alias}"`);
    if (Object.hasOwn(icons, alias)) throw new Error(`icons.json aliases: "${alias}" is already a core icon`);
    if (typeof target !== 'string' || !Object.hasOwn(icons, target)) {
      throw new Error(`icons.json aliases: "${alias}" → "${target}" is not a core icon`);
    }
    aliases[alias] = target;
  }
  const registry = `/* GENERATED by scripts/build-icons.mjs from src/icons/icons.json — do not edit.\n`
    + ` * Geometry: Lucide (ISC; Feather-derived: MIT) — THIRD_PARTY_NOTICES.md; icons with "source": "td" in icons.json\n`
    + ` * are original td artwork (ADR 0039). */\n`
    + `export default ${JSON.stringify(icons, null, 2)};\n\n`
    + `/** Alternative name → core icon name (icons.json "aliases"). */\n`
    + `export const aliases = ${JSON.stringify(aliases, null, 2)};\n`;

  // v0.94.0 (plan §5.2–5.3): search metadata — keys == the icon names, each entry through the shared validator.
  if (!search || typeof search !== 'object' || search.$schema !== SEARCH_SCHEMA) {
    throw new Error(`icons-search.json: "$schema" must be "${SEARCH_SCHEMA}"`);
  }
  const entries = search.icons;
  if (!entries || typeof entries !== 'object' || Array.isArray(entries)) throw new Error('icons-search.json: "icons" must be an object');
  for (const key of Object.keys(entries)) {
    if (Object.hasOwn(aliases, key)) throw new Error(`icons-search.json: "${key}" is an alias (of "${aliases[key]}"), not an icon name`);
    if (!Object.hasOwn(icons, key)) throw new Error(`icons-search.json: "${key}" is not an icon in icons.json`);
  }
  const lines = [];
  for (const name of Object.keys(icons)) {
    if (!Object.hasOwn(entries, name)) throw new Error(`icons-search.json: missing entry for icon "${name}"`);
    let clean;
    try { clean = validateSearchEntry(name, entries[name]); } catch (e) { throw new Error(`icons-search.json: ${e.message}`); }
    lines.push(`  ${JSON.stringify(name)}: ${JSON.stringify(clean)},`);
  }
  const searchOut = `/* GENERATED by scripts/build-icons.mjs from src/icons/icons-search.json — do not edit.\n`
    + ` * Icon search metadata (VI label + EN / VI keywords), one line per icon in icons.json order. Loaded lazily (dynamic\n`
    + ` * import) by td-icon-picker; never imported by td-icon.js. Rules: src/icons/icon-search-schema.js. */\n`
    + `export default Object.freeze({\n${lines.join('\n')}\n});\n`;
  return { registry, search: searchOut, icons: Object.keys(icons).length, aliases: Object.keys(aliases).length };
}

const isMain = process.argv[1] && realpathSync(resolve(process.argv[1])) === realpathSync(fileURLToPath(import.meta.url));
if (isMain) {
  const rootArg = process.argv.indexOf('--root');
  const ROOT = realpathSync(rootArg > 0 ? resolve(process.argv[rootArg + 1]) : join(dirname(fileURLToPath(import.meta.url)), '..'));
  const read = (rel) => JSON.parse(readFileSync(join(ROOT, rel), 'utf8'));
  let out;
  try {
    out = buildIconOutputs(read('src/icons/icons.json'), read('src/icons/icons-search.json'));
  } catch (e) {
    console.error(e.message);
    process.exit(1);
  }
  const files = [['src/icons/registry.js', out.registry], ['src/icons/icons-search.js', out.search]];
  if (process.argv.includes('--check')) {
    const stale = files.filter(([rel, content]) => readGenerated(ROOT, join(ROOT, rel)) !== content).map(([rel]) => rel);
    for (const rel of stale) console.error(`${rel} is stale — run \`npm run build:icons\`.`);
    if (stale.length) process.exit(1);
    console.log('icons registry and search metadata are up to date.');
  } else {
    for (const [rel, content] of files) writeGenerated(ROOT, join(ROOT, rel), content);
    console.log(`src/icons/registry.js written (${out.icons} icons, ${out.aliases} aliases); src/icons/icons-search.js written.`);
  }
}
