#!/usr/bin/env node
/**
 * Build the canonical td.css from src/styles/ per manifest.json (deterministic concat).
 *   node scripts/build-css.mjs          → write td.css
 *   node scripts/build-css.mjs --check  → exit 1 if td.css is missing or stale
 * Sources are plain CSS; `@import` is rejected so the output is self-contained. ADR 0014 (v0.34.0): every `@media` /
 * `@container` must use a kit breakpoint, and each `@container td-*` block gets a generated `@supports not
 * (container-type: inline-size)` viewport fallback (scripts/css-responsive.mjs). ADR 0019 (v0.36.2): `:hover` only inside
 * `@media (hover: hover) and (pointer: fine)`, and every interactive control has a pressed (`:active` /
 * `[data-td-pressed]`) rule outside it (scripts/css-touch.mjs). v0.41.0 (theming QĐ4): every
 * `:root[data-td-theme="dark"]` rule gets a generated `@media (prefers-color-scheme: dark) { :root[data-td-theme="auto"] }`
 * copy right after it; hand-written auto rules are rejected (scripts/css-theme.mjs). v0.42.0 (QĐ15, ADR 0020): colour
 * tokens live on `:root, [data-td-theme]` (theme scopes), geometry on `:root` — checkThemeScope lints both directions.
 * v0.116.0 (ADR 0045 QĐ4): the per-file pipeline is exported (`readStyle`, `transformStyle`, `buildStyles`) so
 * scripts/build-embed.mjs runs the same transforms on its own file list; importing this module builds nothing.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';
import { checkBreakpoints, addContainerFallbacks, expandVariants } from './css-responsive.mjs';
import { checkHoverGate, checkPressed } from './css-touch.mjs';
import { expandAutoTheme, checkThemeScope } from './css-theme.mjs';



const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const STYLES = join(ROOT, 'src', 'styles');
const OUT = join(ROOT, 'td.css');

/** Read one source file of src/styles/ (LF, no trailing whitespace); `@import` throws. */
export async function readStyle(file) {
  const css = (await readFile(join(STYLES, file), 'utf8')).replace(/\r\n/g, '\n').trimEnd();
  if (/^\s*@import\b/m.test(css)) throw new Error(`${file}: @import is not allowed (td.css must be self-contained)`);
  return css;
}

/** The td.css transforms of one source file: variants → container fallbacks → auto theme. Throws on a bad rule. */
export function transformStyle(css, file) {
  const name = `src/styles/${file}`;
  return expandAutoTheme(addContainerFallbacks(expandVariants(css, name), name), name);
}

/**
 * Read, lint and transform `files` (src/styles/-relative, in order).
 * @param {string[]} files
 * @param {{ lint?: boolean }} [opts] lint = the breakpoint / theme-scope / touch gates (td.css always lints)
 * @returns {Promise<{ parts: Array<{ file: string, css: string }>, errors: string[] }>} errors = lint messages
 *   (already grouped per gate, td.css prints them and exits 1)
 */
export async function buildStyles(files, { lint = true } = {}) {
  const parts = [];
  const bpErrors = [];
  const touchErrors = [];
  const touchEntries = [];
  for (const file of files) {
    const css = await readStyle(file);
    if (lint) {
      bpErrors.push(...checkBreakpoints(css, `src/styles/${file}`));
      touchErrors.push(...checkHoverGate(css, `src/styles/${file}`));
      touchEntries.push({ css, file: `src/styles/${file}` });
    }
    parts.push({ file, css: transformStyle(css, file) });
  }
  if (!lint) return { parts, errors: [] };
  if (bpErrors.length) return { parts, errors: [`Breakpoints (ADR 0014):\n  ${bpErrors.join('\n  ')}`] };
  const scopeErrors = checkThemeScope(touchEntries);
  if (scopeErrors.length) return { parts, errors: [`Theme scope (QĐ15, ADR 0020):\n  ${scopeErrors.join('\n  ')}`] };
  touchErrors.push(...checkPressed(touchEntries));
  if (touchErrors.length) {
    return { parts, errors: [`Touch (ADR 0019):\n  ${touchErrors.join('\n  ')}\n  (${touchErrors.length} errors)`] };
  }
  return { parts, errors: [] };
}

/** The td.css manifest (layers.css first). */
export async function readManifest() {
  const manifest = JSON.parse(await readFile(join(STYLES, 'manifest.json'), 'utf8'));
  if (manifest.files[0] !== 'layers.css') {
    throw new Error('manifest: layers.css must be first (it declares the layer order)');
  }
  return manifest;
}

async function main() {
  const manifest = await readManifest();
  let built;
  try {
    built = await buildStyles(manifest.files);
  } catch (e) {
    if (/@import is not allowed/.test(e.message)) throw e;
    console.error(e.message);
    process.exit(1);
  }
  if (built.errors.length) {
    console.error(built.errors.join('\n'));
    process.exit(1);
  }
  const parts = [
    '/*! td.css — GENERATED by scripts/build-css.mjs from src/styles/ (manifest.json). Do not edit. */\n',
    ...built.parts.map(({ file, css }) => `\n/* ---- src/styles/${file} ---- */\n${css}\n`),
  ];
  const out = parts.join('');

  if (process.argv.includes('--check')) {
    let current = '';
    try { current = await readFile(OUT, 'utf8'); } catch { /* missing */ }
    if (current !== out) {
      console.error('td.css is stale — run `npm run build:css` and commit the result.');
      process.exit(1);
    }
    console.log('td.css is up to date.');
  } else {
    await writeFile(OUT, out);
    console.log(`td.css written (${out.length} bytes, ${manifest.files.length} files).`);
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) await main();
